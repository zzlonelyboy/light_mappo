%% Local helpers

function experiments = discoverSensitivityExperiments( ...
    experimentsRoot, requiredLambdaValues)

summaryFiles = dir( ...
    fullfile( ...
    experimentsRoot, ...
    '*', ...
    'ablation_summary.json'));

if isempty(summaryFiles)
    error('No ablation summaries found under: %s', experimentsRoot);
end

candidates = struct( ...
    'lambda', {}, ...
    'root', {}, ...
    'seeds', {}, ...
    'summaryPath', {});

for fileIndex = 1:numel(summaryFiles)

    summaryPath = fullfile( ...
        summaryFiles(fileIndex).folder, ...
        summaryFiles(fileIndex).name);

    try
        record = jsondecode(fileread(summaryPath));
    catch
        continue;
    end

    if ~isfield(record, 'event_likelihood_objective') || ...
            ~isfield(record, 'seeds') || ...
            isempty(record.seeds)
        continue;
    end

    objective = record.event_likelihood_objective;

    fields = { ...
        'detection_loss_weight', ...
        'delay_loss_weight', ...
        'false_alarm_loss_weight'};

    if ~all(isfield(objective, fields))
        continue;
    end

    lambda = double( ...
        objective.false_alarm_loss_weight);

    if ~any(abs(requiredLambdaValues - lambda) < 1e-12) || ...
            abs(objective.detection_loss_weight) > 1e-12 || ...
            abs(objective.delay_loss_weight) > 1e-12
        continue;
    end

    experimentRoot = ...
        summaryFiles(fileIndex).folder;

    experimentSeeds = ...
        sort(double(record.seeds(:)'));

    configPath = fullfile( ...
        experimentRoot, ...
        'runs', ...
        sprintf( ...
        'inter_uav_consistency_seed%d', ...
        experimentSeeds(1)), ...
        'training', ...
        'training_config.json');

    if ~isfile(configPath)
        continue;
    end

    config = jsondecode(fileread(configPath));

    if ~matchesTargetTrainingProtocol( ...
            config, ...
            lambda, ...
            experimentSeeds(1))
        continue;
    end

    candidates(end + 1).lambda = lambda; %#ok<AGROW>
    candidates(end).root = experimentRoot;
    candidates(end).seeds = experimentSeeds;
    candidates(end).summaryPath = summaryPath;

end

if isempty(candidates)
    error('No experiments matched the requested FA-only protocol.');
end

candidateLambdas = [candidates.lambda];

selected = struct( ...
    'lambda', {}, ...
    'root', {}, ...
    'seeds', {}, ...
    'summaryPath', {});

for lambdaIndex = 1:numel(requiredLambdaValues)

    lambda = requiredLambdaValues(lambdaIndex);

    matching = find( ...
        abs(candidateLambdas - lambda) < 1e-12);

    if isempty(matching)
        error( ...
            'Missing sensitivity experiment for lambda_FA=%g.', ...
            lambda);
    end

    if numel(matching) > 1
        paths = strjoin( ...
            {candidates(matching).summaryPath}, ...
            newline);

        error( ...
            'Ambiguous experiments for lambda_FA=%g:\n%s', ...
            lambda, ...
            paths);
    end

    selected(end + 1) = candidates(matching); %#ok<AGROW>

end

[~, order] = sort([selected.lambda]);
experiments = selected(order);

end

function matched = matchesTargetTrainingProtocol( ...
    config, lambda, seed)

fields = { ...
    'model_type', ...
    'hidden_dim', ...
    'num_layers', ...
    'input_encoder_dim', ...
    'class_weighting', ...
    'loss_objective', ...
    'confirmation_steps', ...
    'confirmation_temperature', ...
    'detection_loss_weight', ...
    'delay_loss_weight', ...
    'false_alarm_loss_weight', ...
    'seed', ...
    'feature_names'};

if ~all(isfield(config, fields))
    matched = false;
    return;
end

matched = ...
    strcmp(config.model_type, 'gru') && ...
    config.hidden_dim == 64 && ...
    config.num_layers == 1 && ...
    config.input_encoder_dim == 16 && ...
    strcmp(config.class_weighting, 'none') && ...
    strcmp(config.loss_objective, 'event_likelihood') && ...
    config.confirmation_steps == 5 && ...
    abs(config.confirmation_temperature - 0.1) <= 1e-12 && ...
    abs(config.detection_loss_weight) <= 1e-12 && ...
    abs(config.delay_loss_weight) <= 1e-12 && ...
    abs(config.false_alarm_loss_weight - lambda) <= 1e-12 && ...
    config.seed == seed && ...
    numel(config.feature_names) == 10;

end

function validateTrainingProtocol( ...
    config, lambda, seed, sourcePath)

if ~matchesTargetTrainingProtocol(config, lambda, seed)
    error('Training protocol mismatch: %s', sourcePath);
end

end

function validateEvaluationProtocol( ...
    result, sourcePath)

if ~isfield(result, 'split') || ...
        ~strcmpi(result.split, 'test')
    error('Expected test split: %s', sourcePath);
end

if ~isfield(result, 'confirmation_steps') || ...
        result.confirmation_steps ~= 5
    error('Expected K=5: %s', sourcePath);
end

if ~isfield(result, 'warmup_steps') || ...
        result.warmup_steps ~= 0
    error('Expected warmup=0: %s', sourcePath);
end

if ~isfield(result, 'dt_s') || ...
        abs(result.dt_s - 0.1) > 1e-12
    error('Expected dt=0.1 s: %s', sourcePath);
end

if ~isfield(result, 'probability_threshold') || ...
        abs(result.probability_threshold - 0.5) > 1e-12
    error('Expected threshold=0.5: %s', sourcePath);
end

if ~isfield(result, 'event_matching_policy') || ...
        ~strcmp( ...
        result.event_matching_policy, ...
        'first_alarm_per_attack_event')
    error('Unexpected event-matching policy: %s', sourcePath);
end

if ~isfield(result, 'duplicate_alarm_policy') || ...
        ~strcmp( ...
        result.duplicate_alarm_policy, ...
        'ignored')
    error('Unexpected duplicate-alarm policy: %s', sourcePath);
end

if ~isfield(result, 'aggregate')
    error('Missing aggregate metrics: %s', sourcePath);
end

end

function setYAxisWithMargin( ...
    ax, lowerValues, upperValues, isProbability)

lower = min(lowerValues(:));
upper = max(upperValues(:));

span = upper - lower;

if span <= 0
    span = max(abs(upper), 1.0) * 0.10;
end

margin = 0.14 * span;

lower = lower - margin;
upper = upper + margin;

lower = max(0, lower);

if isProbability
    upper = min(1, upper);
end

if upper <= lower
    upper = lower + max(span, 0.01);
end

ylim(ax, [lower, upper]);

end