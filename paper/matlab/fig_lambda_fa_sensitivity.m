%% Sensitivity to the event-level false-alarm weight lambda_FA

clear;
clc;
close all;

%% Paths and target protocol

scriptDir = fileparts(mfilename('fullpath'));
projectRoot = fileparts(fileparts(scriptDir));
experimentsRoot = fullfile(projectRoot, 'experimentsCubic');

figureOutputDir = fullfile( ...
    projectRoot, 'paper', 'generated_assets', 'figures');

dataOutputDir = fullfile( ...
    projectRoot, 'paper', 'generated_assets', 'data');

if ~exist(figureOutputDir, 'dir')
    mkdir(figureOutputDir);
end

if ~exist(dataOutputDir, 'dir')
    mkdir(dataOutputDir);
end

requiredLambdaValues = [0.5, 1, 2, 4, 8, 16];

% No lambda-to-directory mapping is hard-coded.
experiments = discoverSensitivityExperiments( ...
    experimentsRoot, requiredLambdaValues);

lambdaValues = [experiments.lambda];
seeds = experiments(1).seeds;

numLambda = numel(lambdaValues);
numSeeds = numel(seeds);

%% Metrics

metricFields = { ...
    'event_recall', ...
    'event_precision', ...
    'event_f1', ...
    'delay_mean_s'};

metricTitles = { ...
    '(a) Event Recall', ...
    '(b) Event Precision', ...
    '(c) Event F1', ...
    '(d) Average Detection Delay'};

metricYLabels = { ...
    'Event Recall', ...
    'Event Precision', ...
    'Event F1', ...
    'Average delay (s)'};

numMetrics = numel(metricFields);

% Dimensions: lambda x seed x metric.
metricValues = nan(numLambda, numSeeds, numMetrics);
sourcePaths = strings(numLambda, numSeeds);

%% Read raw per-seed experiment records

for lambdaIndex = 1:numLambda

    experiment = experiments(lambdaIndex);

    if ~isequal(experiment.seeds, seeds)
        error('Seed mismatch in experiment: %s', experiment.root);
    end

    for seedIndex = 1:numSeeds

        seed = seeds(seedIndex);

        runRoot = fullfile( ...
            experiment.root, ...
            'runs', ...
            sprintf('inter_uav_consistency_seed%d', seed));

        evaluationPath = fullfile( ...
            runRoot, ...
            'evaluation_test.json');

        trainingConfigPath = fullfile( ...
            runRoot, ...
            'training', ...
            'training_config.json');

        if ~isfile(evaluationPath)
            error('Missing test evaluation: %s', evaluationPath);
        end

        if ~isfile(trainingConfigPath)
            error('Missing training configuration: %s', ...
                trainingConfigPath);
        end

        evaluation = jsondecode(fileread(evaluationPath));
        trainingConfig = jsondecode(fileread(trainingConfigPath));

        validateEvaluationProtocol( ...
            evaluation, evaluationPath);

        validateTrainingProtocol( ...
            trainingConfig, ...
            experiment.lambda, ...
            seed, ...
            trainingConfigPath);

        aggregate = evaluation.aggregate;

        metricValues(lambdaIndex, seedIndex, 1) = ...
            aggregate.event_recall;

        metricValues(lambdaIndex, seedIndex, 2) = ...
            aggregate.event_precision;

        metricValues(lambdaIndex, seedIndex, 3) = ...
            aggregate.event_f1;

        metricValues(lambdaIndex, seedIndex, 4) = ...
            aggregate.delay_mean_s;

        sourcePaths(lambdaIndex, seedIndex) = ...
            string(evaluationPath);

    end
end

if ~all(isfinite(metricValues(:)))
    error('At least one loaded metric is invalid.');
end

%% Mean and sample standard deviation across seeds

metricMeans = squeeze(mean(metricValues, 2));
metricStds = squeeze(std(metricValues, 0, 2));

assert(isequal(size(metricMeans), [numLambda, numMetrics]));
assert(isequal(size(metricStds), [numLambda, numMetrics]));

%% Export raw values

[lambdaGrid, seedGrid] = ndgrid(lambdaValues, seeds);

rawTable = table( ...
    lambdaGrid(:), ...
    seedGrid(:), ...
    reshape(metricValues(:, :, 1), [], 1), ...
    reshape(metricValues(:, :, 2), [], 1), ...
    reshape(metricValues(:, :, 3), [], 1), ...
    reshape(metricValues(:, :, 4), [], 1), ...
    sourcePaths(:), ...
    'VariableNames', { ...
    'lambda_FA', ...
    'seed', ...
    'event_recall', ...
    'event_precision', ...
    'event_f1', ...
    'delay_mean_s', ...
    'source_evaluation_json'});

%% Export summarized values

summaryTable = table( ...
    lambdaValues(:), ...
    metricMeans(:, 1), metricStds(:, 1), ...
    metricMeans(:, 2), metricStds(:, 2), ...
    metricMeans(:, 3), metricStds(:, 3), ...
    metricMeans(:, 4), metricStds(:, 4), ...
    string({experiments.root})', ...
    'VariableNames', { ...
    'lambda_FA', ...
    'event_recall_mean', ...
    'event_recall_sample_std', ...
    'event_precision_mean', ...
    'event_precision_sample_std', ...
    'event_f1_mean', ...
    'event_f1_sample_std', ...
    'delay_mean_s_mean', ...
    'delay_mean_s_sample_std', ...
    'source_experiment_directory'});

rawCsvPath = fullfile( ...
    dataOutputDir, ...
    'lambda_fa_sensitivity_raw.csv');

summaryCsvPath = fullfile( ...
    dataOutputDir, ...
    'lambda_fa_sensitivity_summary.csv');

writetable(rawTable, rawCsvPath);
writetable(summaryTable, summaryCsvPath);

%% Publication-quality four-panel plot

metricColors = [ ...
    0.0000, 0.4470, 0.7410; ...
    0.8500, 0.3250, 0.0980; ...
    0.0000, 0.6200, 0.4510; ...
    0.4940, 0.1840, 0.5560];

fig = figure( ...
    'Color', 'w', ...
    'Units', 'centimeters', ...
    'Position', [2, 2, 18.0, 13.0]);

layout = tiledlayout( ...
    fig, ...
    2, ...
    2, ...
    'TileSpacing', 'compact', ...
    'Padding', 'compact');

xTickLabels = cellstr(compose('%g', lambdaValues));

for metricIndex = 1:numMetrics

    ax = nexttile(layout, metricIndex);

    hold(ax, 'on');
    box(ax, 'on');
    grid(ax, 'on');

    metricMean = metricMeans(:, metricIndex);
    color = metricColors(metricIndex, :);

    plot( ...
        ax, ...
        lambdaValues, ...
        metricMean, ...
        '-o', ...
        'Color', color, ...
        'MarkerFaceColor', 'w', ...
        'MarkerEdgeColor', color, ...
        'MarkerSize', 5.5, ...
        'LineWidth', 1.45);

    set( ...
        ax, ...
        'XScale', 'log', ...
        'XTick', lambdaValues, ...
        'XTickLabel', xTickLabels, ...
        'XLim', [ ...
        min(lambdaValues) / 1.15, ...
        max(lambdaValues) * 1.15], ...
        'FontName', 'Times New Roman', ...
        'FontSize', 8, ...
        'LineWidth', 0.75, ...
        'TickDir', 'out', ...
        'GridAlpha', 0.16, ...
        'MinorGridAlpha', 0.08, ...
        'Layer', 'top');

    xlabel( ...
        ax, ...
        '$\lambda_{\mathrm{FA}}$', ...
        'Interpreter', 'latex');

    ylabel( ...
        ax, ...
        metricYLabels{metricIndex});

    title( ...
        ax, ...
        metricTitles{metricIndex}, ...
        'FontWeight', 'normal', ...
        'FontSize', 9);

    %% Y-axis settings

    if metricIndex == 1 || metricIndex == 2

        % Event Recall and Event Precision
        ylim(ax, [0.90, 1.00]);
        yticks(ax, 0.90:0.02:1.00);

    else

        % Event F1 and average detection delay
        isProbabilityMetric = (metricIndex == 3);

        setYAxisWithMargin( ...
            ax, ...
            metricMean, ...
            metricMean, ...
            isProbabilityMetric);

    end

end

