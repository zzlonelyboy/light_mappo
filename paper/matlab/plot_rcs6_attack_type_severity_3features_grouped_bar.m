%% Local functions

function startLegendDrag(legendAxis)

    % Identify the parent figure.

    fig = ancestor( ...
        legendAxis, ...
        'figure');

    if isempty(fig) || ~isgraphics(fig)
        return;
    end

    %% Save original units

    originalFigureUnits = ...
        fig.Units;

    originalLegendUnits = ...
        legendAxis.Units;

    %% Convert both figure and legend to pixel coordinates

    fig.Units = ...
        'pixels';

    legendAxis.Units = ...
        'pixels';

    %% Store the initial mouse and legend positions

    startPoint = ...
        fig.CurrentPoint;

    startPosition = ...
        legendAxis.Position;

    %% Store drag information

    dragData.legendAxis = ...
        legendAxis;

    dragData.startPoint = ...
        startPoint;

    dragData.startPosition = ...
        startPosition;

    dragData.originalFigureUnits = ...
        originalFigureUnits;

    dragData.originalLegendUnits = ...
        originalLegendUnits;

    setappdata( ...
        fig, ...
        'LegendDragData', ...
        dragData);

    %% Enable temporary mouse callbacks

    fig.WindowButtonMotionFcn = ...
        @dragLegend;

    fig.WindowButtonUpFcn = ...
        @stopLegendDrag;

end


function dragLegend(fig, ~)

    %% Retrieve drag information

    if ~isappdata(fig, 'LegendDragData')
        return;
    end

    dragData = ...
        getappdata( ...
            fig, ...
            'LegendDragData');

    legendAxis = ...
        dragData.legendAxis;

    if ~isgraphics(legendAxis)
        return;
    end

    %% Calculate mouse displacement

    currentPoint = ...
        fig.CurrentPoint;

    displacement = ...
        currentPoint - ...
        dragData.startPoint;

    %% Update legend position

    newPosition = ...
        dragData.startPosition;

    newPosition(1) = ...
        newPosition(1) + ...
        displacement(1);

    newPosition(2) = ...
        newPosition(2) + ...
        displacement(2);

    legendAxis.Position = ...
        newPosition;

    drawnow limitrate;

end


function stopLegendDrag(fig, ~)

    %% Retrieve drag information

    if ~isappdata(fig, 'LegendDragData')

        fig.WindowButtonMotionFcn = '';
        fig.WindowButtonUpFcn = '';

        return;

    end

    dragData = ...
        getappdata( ...
            fig, ...
            'LegendDragData');

    legendAxis = ...
        dragData.legendAxis;

    %% Restore original coordinate units

    if isgraphics(legendAxis)

        legendAxis.Units = ...
            dragData.originalLegendUnits;

    end

    fig.Units = ...
        dragData.originalFigureUnits;

    %% Remove temporary callbacks

    fig.WindowButtonMotionFcn = '';
    fig.WindowButtonUpFcn = '';

    rmappdata( ...
        fig, ...
        'LegendDragData');

end