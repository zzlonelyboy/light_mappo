%% Matched-RCS = 6 event performance by attack type and severity
%
% Figure layout
%   Rows represent Random, Replay, and Stealth attacks
%   Columns represent Event Recall, Event Precision, Event F1,
%   and Mean Delay
%   The x-axis represents Weak, Medium, and Strong attack severities
%
% Feature representations
%   Position Only   : blue cross hatch
%   Local Features : orange 45-degree hatch
%   Full Features  : green horizontal hatch
%
% Legend
%   The legend is vertically arranged and initially placed at the
%   upper-right corner of the figure.
%
%   The legend can be manually dragged with the mouse.
%
%   After adjusting the legend position, press any key in the MATLAB
%   Command Window to export the final figure.

clear;
close all;
clc;

%% Check required plotting functions

requiredFunctions = { ...
    'hatchfill2', ...
    'legendflex', ...
    'getpos', ...
    'setpos'};

for i = 1:numel(requiredFunctions)

    assert( ...
        exist(requiredFunctions{i}, 'file') == 2, ...
        ['Required plotting function "%s.m" was not found. ' ...
         'Add the complete plotting package to the MATLAB path.'], ...
        requiredFunctions{i});

end

%% Locate the input and output directories

scriptDir = fileparts(mfilename('fullpath'));

if isempty(scriptDir)
    scriptDir = pwd;
end

projectRoot = fileparts(fileparts(scriptDir));

dataDir = fullfile( ...
    projectRoot, ...
    'experimentsCubic', ...
    'mlp16_objective_fa_only', ...
    'cross_rcs_feature_comparison');

dataFile = fullfile( ...
    dataDir, ...
    'cross_rcs_by_attack_type_severity_summary.csv');

figureDir = fullfile( ...
    dataDir, ...
    'matlab_figures');

if ~isfolder(figureDir)
    mkdir(figureDir);
end

assert( ...
    isfile(dataFile), ...
    'Input file was not found at:\n%s', ...
    dataFile);

%% Read and validate the input table

T = readtable( ...
    dataFile, ...
    'TextType', 'string');

requiredVariables = { ...
    'test_rcs', ...
    'feature_set', ...
    'attack_type', ...
    'severity', ...
    'event_recall_mean', ...
    'event_precision_mean', ...
    'event_f1_mean', ...
    'delay_mean_s_mean'};

missingVariables = setdiff( ...
    requiredVariables, ...
    T.Properties.VariableNames);

assert( ...
    isempty(missingVariables), ...
    'The input table is missing variables: %s', ...
    strjoin(missingVariables, ', '));

%% Normalize categorical columns

T.feature_set = lower(strtrim(string(T.feature_set)));
T.attack_type = lower(strtrim(string(T.attack_type)));
T.severity = lower(strtrim(string(T.severity)));

if isnumeric(T.test_rcs)

    testRcs = double(T.test_rcs);

else

    testRcs = str2double(string(T.test_rcs));

end

assert( ...
    all(isfinite(testRcs)), ...
    'Column "test_rcs" contains invalid values.');

%% Select matched RCS = 6 observations

T = T( ...
    testRcs == 6 & ...
    T.attack_type ~= "mixed", ...
    :);

assert( ...
    ~isempty(T), ...
    'No matched RCS = 6 observations were found.');

%% Plot configuration

attackTypes = [ ...
    "random", ...
    "replay", ...
    "stealth"];

attackLabels = { ...
    'Random', ...
    'Replay', ...
    'Stealth'};

severities = [ ...
    "weak", ...
    "medium", ...
    "strong"];

severityLabels = { ...
    'Weak', ...
    'Medium', ...
    'Strong'};

featureSets = [ ...
    "position_only", ...
    "no_neighbor", ...
    "inter_uav_consistency"];

featureLabels = { ...
    'Position Only', ...
    'Local Features', ...
    'Full Features'};

metricNames = [ ...
    "event_recall_mean", ...
    "event_precision_mean", ...
    "event_f1_mean", ...
    "delay_mean_s_mean"];

metricTitles = { ...
    '(a) Event Recall', ...
    '(b) Event Precision', ...
    '(c) Event F1', ...
    '(d) Mean Delay'};

numberOfAttacks = numel(attackTypes);
numberOfSeverities = numel(severities);
numberOfFeatures = numel(featureSets);
numberOfMetrics = numel(metricNames);

%% Color configuration

% Keep the original saturated colors.

featureColors = [ ...
      0, 114, 189; ...
    217,  83,  25; ...
    119, 172,  48] / 255;

% Keep the original pale bar backgrounds.

featureFaceColors = ...
    0.74 * ones(size(featureColors)) + ...
    0.26 * featureColors;

% Keep the original darker same-color borders.

featureEdgeColors = ...
    0.72 * featureColors;

%% Hatch configuration

hatchStyles = { ...
    'cross', ...
    'single', ...
    'single'};

hatchAngles = [ ...
    45, ...
    45, ...
    0];

% Hatch density for the actual bars.

barHatchDensity = [ ...
    38, ...
    42, ...
    42];

% Lower hatch density for the much smaller legend symbols.

legendHatchDensity = [ ...
    14, ...
    18, ...
    18];

hatchLineWidth = 0.60;

%% Assemble all plotting values before drawing

% Dimensions:
%   severity x feature x attack x metric

plotValues = nan( ...
    numberOfSeverities, ...
    numberOfFeatures, ...
    numberOfAttacks, ...
    numberOfMetrics);

for ai = 1:numberOfAttacks

    for si = 1:numberOfSeverities

        for fi = 1:numberOfFeatures

            mask = ...
                T.attack_type == attackTypes(ai) & ...
                T.severity == severities(si) & ...
                T.feature_set == featureSets(fi);

            D = T(mask, :);

            assert( ...
                height(D) == 1, ...
                ['Expected exactly one row for attack "%s", ' ...
                 'severity "%s", and feature set "%s". ' ...
                 'Found %d rows.'], ...
                attackTypes(ai), ...
                severities(si), ...
                featureSets(fi), ...
                height(D));

            for mi = 1:numberOfMetrics

                metricName = char(metricNames(mi));
                value = D.(metricName);

                assert( ...
                    isnumeric(value) && ...
                    isscalar(value) && ...
                    isfinite(value), ...
                    ['Metric "%s" must contain one finite numeric value ' ...
                     'for %s, %s, and %s.'], ...
                    metricName, ...
                    attackTypes(ai), ...
                    severities(si), ...
                    featureSets(fi));

                plotValues(si, fi, ai, mi) = ...
                    double(value);

            end

        end

    end

end

%% Determine a shared delay-axis range

delayValues = ...
    plotValues(:, :, :, 4);

maximumDelay = ...
    max(delayValues(:));

if maximumDelay <= 0

    delayUpperLimit = 1;

else

    rawUpperLimit = ...
        1.10 * maximumDelay;

    orderOfMagnitude = ...
        10 ^ floor(log10(rawUpperLimit));

    normalizedLimit = ...
        rawUpperLimit / orderOfMagnitude;

    niceMultipliers = [ ...
        1, ...
        1.2, ...
        1.5, ...
        2, ...
        2.5, ...
        3, ...
        4, ...
        5, ...
        6, ...
        8, ...
        10];

    multiplierIndex = find( ...
        niceMultipliers >= normalizedLimit, ...
        1, ...
        'first');

    if isempty(multiplierIndex)
        multiplierIndex = numel(niceMultipliers);
    end

    delayUpperLimit = ...
        niceMultipliers(multiplierIndex) * ...
        orderOfMagnitude;

end

%% Create the figure

fig = figure( ...
    'Color', 'w', ...
    'Units', 'centimeters', ...
    'Position', [1, 1, 31.5, 23.5], ...
    'PaperPositionMode', 'auto', ...
    'Renderer', 'painters');

tl = tiledlayout( ...
    fig, ...
    numberOfAttacks, ...
    numberOfMetrics, ...
    'TileSpacing', 'compact', ...
    'Padding', 'compact');

try

    tl.OuterPosition = [ ...
        0.055, ...
        0.055, ...
        0.925, ...
        0.845];

catch

    % OuterPosition may be unavailable in older MATLAB versions.

end

axesHandles = gobjects( ...
    numberOfAttacks, ...
    numberOfMetrics);

legendHandles = gobjects( ...
    numberOfFeatures, ...
    1);

x = 1:numberOfSeverities;

%% Draw the subplots

for ai = 1:numberOfAttacks

    for mi = 1:numberOfMetrics

        tileIndex = ...
            (ai - 1) * numberOfMetrics + mi;

        ax = nexttile( ...
            tl, ...
            tileIndex);

        axesHandles(ai, mi) = ax;

        hold(ax, 'on');

        values = ...
            plotValues(:, :, ai, mi);

        %% Draw grouped bars

        bars = bar( ...
            ax, ...
            x, ...
            values, ...
            'grouped', ...
            'BarWidth', 0.82);

        %% Apply bar colors and hatches

        for fi = 1:numberOfFeatures

            bars(fi).FaceColor = ...
                featureFaceColors(fi, :);

            bars(fi).EdgeColor = ...
                featureEdgeColors(fi, :);

            bars(fi).LineWidth = ...
                0.90;

            hatchHandles = hatchfill2( ...
                bars(fi), ...
                hatchStyles{fi}, ...
                'HatchAngle', ...
                hatchAngles(fi), ...
                'HatchDensity', ...
                barHatchDensity(fi), ...
                'HatchColor', ...
                featureColors(fi, :), ...
                'HatchLineWidth', ...
                hatchLineWidth);

            if ~isempty(hatchHandles)

                try

                    set( ...
                        hatchHandles, ...
                        'HandleVisibility', ...
                        'off');

                catch
                end

            end

            % Use bars from the first subplot as legend sources.

            if ai == 1 && mi == 1

                legendHandles(fi) = ...
                    bars(fi);

            else

                bars(fi).HandleVisibility = ...
                    'off';

            end

        end

        %% Configure x-axis

        xlim( ...
            ax, ...
            [0.5, numberOfSeverities + 0.5]);

        xticks( ...
            ax, ...
            x);

        if ai == numberOfAttacks

            xticklabels( ...
                ax, ...
                severityLabels);

            xlabel( ...
                ax, ...
                'Attack Severity');

        else

            xticklabels( ...
                ax, ...
                {});

        end

        %% Configure column titles

