%% Long-duration evaluation of the Proposed detector

clear;
clc;
close all;

%% Paths

scriptDir = fileparts(mfilename('fullpath'));

if isempty(scriptDir)
    scriptDir = pwd;
end

projectRoot = fileparts(fileparts(scriptDir));
experimentRoot = fullfile( ...
    projectRoot, 'experimentsCubic', 'mlp16_objective_fa_only');

runsRoot = fullfile(experimentRoot, 'runs');

figureOutputDir = fullfile( ...
    projectRoot, 'paper', 'generated_assets', 'figures');

dataOutputDir = fullfile( ...
    projectRoot, 'paper', 'generated_assets', 'data');

if ~isfolder(figureOutputDir)
    mkdir(figureOutputDir);
end

if ~isfolder(dataOutputDir)
    mkdir(dataOutputDir);
end

assert(isfolder(runsRoot), 'Missing runs directory:\n%s', runsRoot);

%% Analysis configuration

seeds = [20260716, 20260717, 20260718];
quarterFields = { ...
    'quarter_1', ...
    'quarter_2', ...
    'quarter_3', ...
    'quarter_4' ...
};

quarterLabels = { ...
    '0--15', ...
    '15--30', ...
    '30--45', ...
    '45--60' ...
};

nSeed = numel(seeds);
nQuarter = numel(quarterFields);

quarterRecall = nan(nSeed, nQuarter);
quarterPrecision = nan(nSeed, nQuarter);
quarterF1 = nan(nSeed, nQuarter);
quarterDelay = nan(nSeed, nQuarter);

aggregateMetrics = nan(nSeed, 3);
aggregateDelay = nan(nSeed, 1);
cleanAlarmProbability = nan(nSeed, 1);

evaluationPaths = strings(nSeed, 1);
summaryPaths = strings(nSeed, 1);

referenceCounts = [];

%% Discover and read the raw three-seed records

for seedIndex = 1:nSeed

    seed = seeds(seedIndex);

    runRoot = fullfile( ...
        runsRoot, ...
        sprintf('inter_uav_consistency_seed%d', seed));

    assert(isfolder(runRoot), ...
        'Missing Proposed run directory:\n%s', runRoot);

    evaluationMatches = dir(fullfile( ...
        runRoot, 'cross_test', '**', ...
        'evaluation_d5_long_multiattack.json'));

    assert(numel(evaluationMatches) == 1, ...
        ['Expected one long-duration evaluation for seed %d, ' ...
         'but found %d.'], seed, numel(evaluationMatches));

    evaluationPath = fullfile( ...
        evaluationMatches(1).folder, evaluationMatches(1).name);

    summaryPath = fullfile( ...
        evaluationMatches(1).folder, ...
        'summary_d5_long_multiattack.json');

    assert(isfile(summaryPath), ...
        'Missing long-duration summary:\n%s', summaryPath);

    evaluation = jsondecode(fileread(evaluationPath));
    summary = jsondecode(fileread(summaryPath));

    validateEvaluation(evaluation, evaluationPath);
    validateSummary(summary, summaryPath);

    evaluationPaths(seedIndex) = string(evaluationPath);
    summaryPaths(seedIndex) = string(summaryPath);

    counts = [ ...
        double(evaluation.dataset_counts.episodes), ...
        double(evaluation.dataset_counts.clean_episodes), ...
        double(evaluation.dataset_counts.group_attack_events), ...
        double(evaluation.dataset_counts.per_uav_attack_events) ...
    ];

    if isempty(referenceCounts)
        referenceCounts = counts;
    else
        assert(isequal(counts, referenceCounts), ...
            'The long-duration dataset counts differ across seeds.');
    end

    for quarterIndex = 1:nQuarter

        quarter = evaluation.by_time_quarter.( ...
            quarterFields{quarterIndex});

        quarterRecall(seedIndex, quarterIndex) = ...
            double(quarter.event_recall);

        detectedEvents = double(quarter.detected_events);
        falsePositives = double(quarter.false_positives);

        quarterPrecision(seedIndex, quarterIndex) = ...
            safeDivide(detectedEvents, detectedEvents + falsePositives);

        quarterF1(seedIndex, quarterIndex) = ...
            safeF1( ...
            quarterPrecision(seedIndex, quarterIndex), ...
            quarterRecall(seedIndex, quarterIndex));

        quarterDelay(seedIndex, quarterIndex) = ...
            double(quarter.delay_mean_s);
    end

    aggregateMetrics(seedIndex, :) = [ ...
        double(summary.event_recall), ...
        double(summary.event_precision), ...
        double(summary.event_f1) ...
    ];

    aggregateDelay(seedIndex) = double(summary.delay_mean_s);

    cleanAlarmProbability(seedIndex) = ...
        double(summary.clean_episode_stability. ...
        clean_episode_alarm_probability);
end

assert(all(isfinite(quarterRecall(:))), ...
    'At least one quarter-level recall is invalid.');

assert(all(isfinite(quarterPrecision(:))), ...
    'At least one quarter-level precision is invalid.');

assert(all(isfinite(quarterF1(:))), ...
    'At least one quarter-level F1 score is invalid.');

assert(all(isfinite(quarterDelay(:))), ...
    'At least one quarter-level delay is invalid.');

assert(all(isfinite(aggregateMetrics(:))), ...
    'At least one aggregate metric is invalid.');

assert(all(isfinite(aggregateDelay(:))), ...
    'At least one aggregate delay is invalid.');

assert(all(cleanAlarmProbability == 0), ...
    'At least one clean long-duration episode contains an alarm.');

%% Export the exact values used by the figure

quarterTable = table();

for seedIndex = 1:nSeed
    current = table( ...
        repmat(seeds(seedIndex), nQuarter, 1), ...
        (1:nQuarter)', ...
        string(quarterLabels)', ...
        quarterRecall(seedIndex, :)', ...
        quarterPrecision(seedIndex, :)', ...
        quarterF1(seedIndex, :)', ...
        quarterDelay(seedIndex, :)', ...
        repmat(evaluationPaths(seedIndex), nQuarter, 1), ...
        'VariableNames', { ...
        'training_seed', ...
        'time_quarter', ...
        'time_range_min', ...
        'event_recall', ...
        'event_precision', ...
        'event_f1', ...
        'delay_mean_s', ...
        'source_evaluation_json'});

    if seedIndex == 1
        quarterTable = current;
    else
        quarterTable = [quarterTable; current]; %#ok<AGROW>
    end
end

aggregateTable = table( ...
    seeds(:), ...
    aggregateMetrics(:, 1), ...
    aggregateMetrics(:, 2), ...
    aggregateMetrics(:, 3), ...
    aggregateDelay, ...
    cleanAlarmProbability, ...
    summaryPaths, ...
    'VariableNames', { ...
    'training_seed', ...
    'event_recall', ...
    'event_precision', ...
    'event_f1', ...
    'delay_mean_s', ...
    'clean_episode_alarm_probability', ...
    'source_summary_json'});

quarterOutputFile = fullfile( ...
    dataOutputDir, 'fig_long_duration_quarter_data.csv');

aggregateOutputFile = fullfile( ...
    dataOutputDir, 'fig_long_duration_aggregate_data.csv');

writetable(quarterTable, quarterOutputFile);
writetable(aggregateTable, aggregateOutputFile);

%% Plot

proposedColor = [0.0000, 0.5000, 0.4500];
seedColor = 0.68 * [1, 1, 1];

% Dimensions are seed x time quarter x metric.
quarterMetrics = nan(nSeed, nQuarter, 4);
quarterMetrics(:, :, 1) = quarterRecall;
quarterMetrics(:, :, 2) = quarterPrecision;
quarterMetrics(:, :, 3) = quarterF1;
quarterMetrics(:, :, 4) = quarterDelay;

metricTitles = { ...
    '(a) Event Recall', ...
    '(b) Event Precision', ...
    '(c) Event F1', ...
    '(d) Average detection delay' ...
};

metricYLabels = { ...
    'Event Recall', ...
    'Event Precision', ...
    'Event F1', ...
    'Average delay (s)' ...
};

fig = figure( ...
    'Color', 'w', ...
    'Units', 'centimeters', ...
    'Position', [2, 2, 17.8, 12.2]);

layout = tiledlayout( ...
    fig, 2, 2, ...
    'TileSpacing', 'compact', ...
    'Padding', 'compact');

for metricIndex = 1:4

    ax = nexttile(layout, metricIndex);
    hold(ax, 'on');
    box(ax, 'on');
    grid(ax, 'on');

    seedHandle = gobjects(1, 1);

    for seedIndex = 1:nSeed
        handle = plot( ...
            ax, 1:nQuarter, ...
            quarterMetrics(seedIndex, :, metricIndex), ...
            '-o', ...
            'Color', seedColor, ...
            'MarkerFaceColor', 'w', ...
            'MarkerSize', 3.5, ...
            'LineWidth', 0.8);

        if seedIndex == 1
            seedHandle = handle;
        else
            handle.HandleVisibility = 'off';
        end
    end

    values = quarterMetrics(:, :, metricIndex);
    metricMean = mean(values, 1);
    metricStd = std(values, 0, 1);

    meanHandle = errorbar( ...
        ax, 1:nQuarter, metricMean, metricStd, ...
        '-o', ...
        'Color', proposedColor, ...
        'MarkerFaceColor', proposedColor, ...
        'MarkerSize', 5.0, ...
        'LineWidth', 1.7, ...
        'CapSize', 4);

    styleQuarterAxes(ax, quarterLabels);

    if metricIndex <= 3
        ylim(ax, [0.90, 1.00]);
    else
        setAxisWithMargin( ...
            ax, values, zeros(size(values)), false);
    end

    ylabel(ax, metricYLabels{metricIndex});

    title( ...
        ax, metricTitles{metricIndex}, ...
        'FontWeight', 'normal', ...
        'FontSize', 9);

    if metricIndex == 1
        legend( ...
            ax, [seedHandle, meanHandle], ...
            {'Individual seeds', 'Mean \pm sample SD'}, ...
            'Location', 'southwest', ...
            'FontName', 'Times New Roman', ...
            'FontSize', 7.5, ...
            'Box', 'off');
    else
        seedHandle.HandleVisibility = 'off';
        meanHandle.HandleVisibility = 'off';
    end

    hold(ax, 'off');
end

datasetNote = sprintf( ...
    ['%d x 1 h episodes, %d group attacks, %d UAV-level attacks, ' ...
     '%d clean episodes with no alarms'], ...
    referenceCounts(1), ...
    referenceCounts(3), ...
    referenceCounts(4), ...
    referenceCounts(2));

annotation( ...
    fig, 'textbox', [0.10, 0.005, 0.82, 0.035], ...
    'String', datasetNote, ...
    'HorizontalAlignment', 'center', ...
    'VerticalAlignment', 'middle', ...
    'FontName', 'Times New Roman', ...
    'FontSize', 7.5, ...
    'EdgeColor', 'none');

%% Export

outputBase = fullfile( ...
    figureOutputDir, 'fig_long_duration_evaluation');

exportgraphics(fig, [outputBase, '.png'], 'Resolution', 600);
exportgraphics(fig, [outputBase, '.pdf'], 'ContentType', 'vector');
savefig(fig, [outputBase, '.fig']);

fprintf('Quarter-level figure data\n%s\n\n', quarterOutputFile);
fprintf('Aggregate figure data\n%s\n\n', aggregateOutputFile);
fprintf('Figure prefix\n%s\n', outputBase);

%% Local helpers

function validateEvaluation(evaluation, sourcePath)

requiredFields = { ...
    'feature_set', ...
    'dt_s', ...
    'confirmation_steps', ...
    'probability_threshold', ...
    'dataset_counts', ...
    'by_time_quarter' ...
};

assert(all(isfield(evaluation, requiredFields)), ...
    'Missing required fields in %s.', sourcePath);

assert(strcmp(evaluation.feature_set, 'inter_uav_consistency'), ...
    'Expected the Proposed feature set in %s.', sourcePath);

assert(abs(double(evaluation.dt_s) - 0.1) < 1e-12, ...
    'Expected dt=0.1 s in %s.', sourcePath);

assert(double(evaluation.confirmation_steps) == 5, ...
    'Expected K=5 in %s.', sourcePath);

assert(abs(double(evaluation.probability_threshold) - 0.5) < 1e-12, ...
    'Expected threshold=0.5 in %s.', sourcePath);

end

function validateSummary(summary, sourcePath)

requiredFields = { ...
    'event_precision', ...
    'event_recall', ...
    'event_f1', ...
    'delay_mean_s', ...
    'clean_episode_stability' ...
};

assert(all(isfield(summary, requiredFields)), ...
    'Missing required fields in %s.', sourcePath);

end

function value = safeDivide(numerator, denominator)

if denominator <= 0
    value = 0;
else
    value = numerator / denominator;
end

end

function value = safeF1(precision, recall)

if precision + recall <= 0
    value = 0;
else
    value = 2 * precision * recall / (precision + recall);
end

end

function styleQuarterAxes(ax, labels)

set( ...
    ax, ...
    'XTick', 1:numel(labels), ...
    'XTickLabel', labels, ...
    'XLim', [0.75, numel(labels) + 0.25], ...
    'FontName', 'Times New Roman', ...
    'FontSize', 8, ...
    'LineWidth', 0.75, ...
    'TickDir', 'out', ...
    'GridAlpha', 0.16, ...
    'MinorGridAlpha', 0.08, ...
    'Layer', 'top');

xlabel(ax, 'Elapsed time (min)');

end

function setAxisWithMargin(ax, values, errors, isProbability)

lower = min(values(:) - errors(:));
upper = max(values(:) + errors(:));
span = upper - lower;

if span <= 0
    span = max(abs(upper), 1) * 0.1;
end

lower = max(0, lower - 0.14 * span);
upper = upper + 0.14 * span;

if isProbability
    upper = min(1, upper);
end

ylim(ax, [lower, upper]);

end
