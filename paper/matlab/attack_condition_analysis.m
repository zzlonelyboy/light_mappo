%% plot_attack_condition_3features.m
% Attack-condition analysis under three feature configurations
%
% Rows
%   Random attack
%   Replay attack
%   Stealth attack
%
% Columns
%   Event Precision
%   Event Recall
%   Event F1
%   Mean Delay
%
% Each curve represents one feature configuration.
% The plotted values are calculated from per-seed evaluation records.

clear;
close all;
clc;

%% 1. Paths

% Derive the project directory from this script so that the analysis does
% not depend on a machine-specific absolute path.
scriptDir = fileparts(mfilename('fullpath'));

if isempty(scriptDir)
    scriptDir = pwd;
end

projectRoot = fileparts(fileparts(scriptDir));
experimentsRoot = fullfile(projectRoot, 'experimentsCubic');
experimentDir = fullfile(experimentsRoot, 'mlp16_objective_fa_only');

dataFile = fullfile( ...
    experimentDir, ...
    'cross_rcs_feature_comparison', ...
    'cross_rcs_by_attack_type_severity_per_seed.csv');

outputDir = fullfile(scriptDir, 'attack_condition_figures');

if ~isfolder(outputDir)
    mkdir(outputDir);
end

assert(isfile(dataFile), ...
    'Experiment record file does not exist:\n%s', dataFile);

%% 2. Plot configuration

targetRCS = 6;

expectedSeeds = [ ...
    20260716, ...
    20260717, ...
    20260718 ...
];

attackTypes = [ ...
    "random", ...
    "replay", ...
    "stealth" ...
];

attackLabels = { ...
    'Random Attack', ...
    'Replay Attack', ...
    'Stealth Attack' ...
};

severityNames = [ ...
    "weak", ...
    "medium", ...
    "strong" ...
];

severityLabels = { ...
    'Weak', ...
    'Medium', ...
    'Strong' ...
};

featureSets = [ ...
    "position_only", ...
    "no_neighbor", ...
    "inter_uav_consistency" ...
];

featureLabels = { ...
    'Position Only', ...
    'Local Features', ...
    'Full Features' ...
};

metricVariables = [ ...
    "event_precision", ...
    "event_recall", ...
    "event_f1", ...
    "delay_mean_s" ...
];

metricTitles = { ...
    'Event Precision', ...
    'Event Recall', ...
    'Event F1', ...
    'Mean Delay (s)' ...
};

colors = [ ...
    0.00, 0.45, 0.74
    0.85, 0.33, 0.10
    0.47, 0.67, 0.19
];

lineStyles = {'--', '-.', '-'};
markers = {'o', 's', '^'};

% Set this to false if error bars are not required.
showErrorBars = true;

%% 3. Read the per-seed experiment records

T = readtable(dataFile, 'TextType', 'string');

requiredVariables = [ ...
    "test_rcs", ...
    "feature_set", ...
    "training_seed", ...
    "attack_type", ...
    "severity", ...
    "event_precision", ...
    "event_recall", ...
    "event_f1", ...
    "delay_mean_s" ...
];

availableVariables = string(T.Properties.VariableNames);
missingVariables = setdiff(requiredVariables, availableVariables);

assert(isempty(missingVariables), ...
    'Missing columns in the experiment record:\n%s', ...
    strjoin(missingVariables, ', '));

% Normalize text fields.
T.feature_set = lower(strtrim(string(T.feature_set)));
T.attack_type = lower(strtrim(string(T.attack_type)));
T.severity = lower(strtrim(string(T.severity)));

%% 4. Select the required evaluation setting

keepRows = ...
    T.test_rcs == targetRCS & ...
    ismember(T.attack_type, attackTypes) & ...
    ismember(T.severity, severityNames) & ...
    ismember(T.feature_set, featureSets);

T = T(keepRows, :);

nAttack = numel(attackTypes);
nSeverity = numel(severityNames);
nFeature = numel(featureSets);
nMetric = numel(metricVariables);

expectedRowCount = ...
    nAttack * nSeverity * nFeature * numel(expectedSeeds);

assert(height(T) == expectedRowCount, ...
    ['Expected %d records, but found %d records.\n' ...
     'Please check the RCS setting, feature names, and random seeds.'], ...
    expectedRowCount, height(T));

%% 5. Aggregate the per-seed results

% Dimensions
% attack type × metric × feature configuration × severity
meanValues = nan(nAttack, nMetric, nFeature, nSeverity);
stdValues = nan(nAttack, nMetric, nFeature, nSeverity);

nCombinations = nAttack * nSeverity * nFeature;

summaryAttack = strings(nCombinations, 1);
summarySeverity = strings(nCombinations, 1);
summaryFeature = strings(nCombinations, 1);
summaryNumSeeds = zeros(nCombinations, 1);

precisionMean = nan(nCombinations, 1);
precisionStd = nan(nCombinations, 1);
recallMean = nan(nCombinations, 1);
recallStd = nan(nCombinations, 1);
f1Mean = nan(nCombinations, 1);
f1Std = nan(nCombinations, 1);
delayMean = nan(nCombinations, 1);
delayStd = nan(nCombinations, 1);

summaryIndex = 0;

for attackIndex = 1:nAttack
    for severityIndex = 1:nSeverity
        for featureIndex = 1:nFeature

            rowMask = ...
                T.attack_type == attackTypes(attackIndex) & ...
                T.severity == severityNames(severityIndex) & ...
                T.feature_set == featureSets(featureIndex);

            D = T(rowMask, :);

            actualSeeds = sort(double(D.training_seed(:)))';
            requiredSeeds = sort(expectedSeeds);

            assert(isequal(actualSeeds, requiredSeeds), ...
                ['Incomplete or duplicated random seeds for\n' ...
                 'attack_type = %s\nseverity = %s\nfeature_set = %s'], ...
                attackTypes(attackIndex), ...
                severityNames(severityIndex), ...
                featureSets(featureIndex));

            for metricIndex = 1:nMetric

                metricName = char(metricVariables(metricIndex));
                values = double(D.(metricName));

                assert(all(isfinite(values)), ...
                    ['Invalid metric values for\n' ...
                     'attack_type = %s\nseverity = %s\n' ...
                     'feature_set = %s\nmetric = %s'], ...
                    attackTypes(attackIndex), ...
                    severityNames(severityIndex), ...
                    featureSets(featureIndex), ...
                    metricVariables(metricIndex));

                meanValues( ...
                    attackIndex, ...
                    metricIndex, ...
                    featureIndex, ...
                    severityIndex) = mean(values);

                % Sample standard deviation across random seeds.
                stdValues( ...
                    attackIndex, ...
                    metricIndex, ...
                    featureIndex, ...
                    severityIndex) = std(values, 0);
            end

            summaryIndex = summaryIndex + 1;

            summaryAttack(summaryIndex) = ...
                attackTypes(attackIndex);

            summarySeverity(summaryIndex) = ...
                severityNames(severityIndex);

            summaryFeature(summaryIndex) = ...
                featureSets(featureIndex);

            summaryNumSeeds(summaryIndex) = height(D);

            precisionMean(summaryIndex) = ...
                meanValues(attackIndex, 1, featureIndex, severityIndex);

            precisionStd(summaryIndex) = ...
                stdValues(attackIndex, 1, featureIndex, severityIndex);

            recallMean(summaryIndex) = ...
                meanValues(attackIndex, 2, featureIndex, severityIndex);

            recallStd(summaryIndex) = ...
                stdValues(attackIndex, 2, featureIndex, severityIndex);

            f1Mean(summaryIndex) = ...
                meanValues(attackIndex, 3, featureIndex, severityIndex);

            f1Std(summaryIndex) = ...
                stdValues(attackIndex, 3, featureIndex, severityIndex);

            delayMean(summaryIndex) = ...
                meanValues(attackIndex, 4, featureIndex, severityIndex);

            delayStd(summaryIndex) = ...
                stdValues(attackIndex, 4, featureIndex, severityIndex);
        end
    end
end

%% 6. Save the MATLAB-generated summary

summaryTable = table( ...
    summaryAttack, ...
    summarySeverity, ...
    summaryFeature, ...
    summaryNumSeeds, ...
    precisionMean, ...
    precisionStd, ...
    recallMean, ...
    recallStd, ...
    f1Mean, ...
    f1Std, ...
    delayMean, ...
    delayStd, ...
    'VariableNames', { ...
        'attack_type', ...
        'severity', ...
        'feature_set', ...
        'num_seeds', ...
        'event_precision_mean', ...
        'event_precision_std', ...
        'event_recall_mean', ...
        'event_recall_std', ...
        'event_f1_mean', ...
        'event_f1_std', ...
        'delay_mean_s', ...
        'delay_std_s' ...
    });

summaryFile = fullfile( ...
    outputDir, ...
    'attack_type_severity_3features_summary_matlab.csv');

writetable(summaryTable, summaryFile);

%% 7. Determine a common range for the delay panels

delayUpperValues = ...
    meanValues(:, 4, :, :) + stdValues(:, 4, :, :);

maximumDelay = max(delayUpperValues(:));
delayUpperLimit = ceil(1.10 * maximumDelay * 2) / 2;

if delayUpperLimit <= 0
    delayUpperLimit = 1;
end

%% 8. Generate the 3-by-4 line-plot matrix

figureHandle = figure( ...
    'Color', 'w', ...
    'Units', 'centimeters', ...
    'Position', [2, 2, 32, 22]);

layoutHandle = tiledlayout( ...
    figureHandle, ...
    nAttack, ...
    nMetric, ...
    'TileSpacing', 'compact', ...
    'Padding', 'compact');

xValues = 1:nSeverity;
legendHandles = gobjects(nFeature, 1);
firstAxes = gobjects(1);

for attackIndex = 1:nAttack
    for metricIndex = 1:nMetric

        axesHandle = nexttile(layoutHandle);
        hold(axesHandle, 'on');

        if attackIndex == 1 && metricIndex == 1
            firstAxes = axesHandle;
        end

        for featureIndex = 1:nFeature

            yValues = squeeze(meanValues( ...
                attackIndex, ...
                metricIndex, ...
                featureIndex, ...
                :));

            errorValues = squeeze(stdValues( ...
                attackIndex, ...
                metricIndex, ...
                featureIndex, ...
                :));

            if showErrorBars
                plotHandle = errorbar( ...
                    axesHandle, ...
                    xValues, ...
                    yValues, ...
                    errorValues, ...
                    'Color', colors(featureIndex, :), ...
                    'LineStyle', lineStyles{featureIndex}, ...
                    'Marker', markers{featureIndex}, ...
                    'LineWidth', 1.35, ...
                    'MarkerSize', 5.5, ...
                    'MarkerFaceColor', 'w', ...
                    'CapSize', 5);
            else
                plotHandle = plot( ...
                    axesHandle, ...
                    xValues, ...
                    yValues, ...
                    'Color', colors(featureIndex, :), ...
                    'LineStyle', lineStyles{featureIndex}, ...
                    'Marker', markers{featureIndex}, ...
                    'LineWidth', 1.35, ...
                    'MarkerSize', 5.5, ...
                    'MarkerFaceColor', 'w');
            end

            if attackIndex == 1 && metricIndex == 1
                legendHandles(featureIndex) = plotHandle;
            end
        end

        grid(axesHandle, 'on');
        box(axesHandle, 'on');

        axesHandle.XTick = xValues;
        axesHandle.XTickLabel = severityLabels;
        axesHandle.XLim = [0.75, nSeverity + 0.25];

        axesHandle.FontName = 'Times New Roman';
        axesHandle.FontSize = 8.5;
        axesHandle.LineWidth = 0.8;
        axesHandle.TickDir = 'out';

        if metricIndex <= 3
            ylim(axesHandle, [0, 1.02]);
            axesHandle.YTick = 0:0.2:1.0;
        else
            ylim(axesHandle, [0, delayUpperLimit]);
        end

        if attackIndex == 1
            title( ...
                axesHandle, ...
                metricTitles{metricIndex}, ...
                'FontName', 'Times New Roman', ...
                'FontSize', 10, ...
                'FontWeight', 'normal');
        end

        if metricIndex == 1
            ylabel( ...
                axesHandle, ...
                attackLabels{attackIndex}, ...
                'FontName', 'Times New Roman', ...
                'FontSize', 9.5, ...
                'FontWeight', 'normal');
        end

        if attackIndex == nAttack
            xlabel( ...
                axesHandle, ...
                'Attack Severity', ...
                'FontName', 'Times New Roman', ...
                'FontSize', 9);
        end

        hold(axesHandle, 'off');
    end
end

%% 9. Add a common legend

legendHandle = legend( ...
    firstAxes, ...
    legendHandles, ...
    featureLabels, ...
    'Orientation', 'horizontal', ...
    'NumColumns', nFeature, ...
    'FontName', 'Times New Roman', ...
    'FontSize', 9, ...
    'Box', 'off');

legendHandle.Layout.Tile = 'north';

%% 10. Export the figure

outputBase = fullfile( ...
    outputDir, ...
    'attack_type_severity_3features');

exportgraphics( ...
    figureHandle, ...
    [outputBase, '.png'], ...
    'Resolution', 600);

exportgraphics( ...
    figureHandle, ...
    [outputBase, '.pdf'], ...
    'ContentType', 'vector');

print( ...
    figureHandle, ...
    [outputBase, '.eps'], ...
    '-depsc', ...
    '-painters');

savefig(figureHandle, [outputBase, '.fig']);

fprintf('Experiment records read from\n%s\n\n', dataFile);
fprintf('Aggregated results saved to\n%s\n\n', summaryFile);
fprintf('Figures saved with prefix\n%s\n', outputBase);
