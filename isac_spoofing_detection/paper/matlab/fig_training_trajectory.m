%% Training trajectory from the recorded Cubic dataset

clear;
clc;
close all;

%% Paths and reproducible data selection

scriptDir = fileparts(mfilename('fullpath'));

if isempty(scriptDir)
    scriptDir = pwd;
end

projectRoot = fileparts(fileparts(scriptDir));

datasetRoot = fullfile( ...
    projectRoot, ...
    'dataCubic', ...
    'd1_5000_scurve_cubic_rcs6_seed20260714_interuav');

manifestFile = fullfile(datasetRoot, 'manifest.json');
pythonExporter = fullfile( ...
    projectRoot, 'scripts', 'plot_training_trajectory.py');

figureOutputDir = fullfile( ...
    projectRoot, 'paper', 'generated_assets', 'figures');

dataOutputDir = fullfile( ...
    projectRoot, 'paper', 'generated_assets', 'data');

outputBase = fullfile( ...
    figureOutputDir, 'fig_training_trajectory_matlab');

dataFile = fullfile( ...
    dataOutputDir, 'fig_training_trajectory_matlab_data.csv');

assert(isfolder(datasetRoot), ...
    'Missing training dataset:\n%s', datasetRoot);

assert(isfile(manifestFile), ...
    'Missing training manifest:\n%s', manifestFile);

assert(isfile(pythonExporter), ...
    'Missing NPZ trajectory exporter:\n%s', pythonExporter);

if ~isfolder(figureOutputDir)
    mkdir(figureOutputDir);
end

if ~isfolder(dataOutputDir)
    mkdir(dataOutputDir);
end

%% User-adjustable configuration

episodeIndex = 0;             % Zero-based index in the training split.
refreshDataFromNpz = true;    % Keep the MATLAB figure tied to raw NPZ data.
pythonCommand = 'python';

if refreshDataFromNpz || ~isfile(dataFile)
    command = sprintf( ...
        ['"%s" "%s" --data-dir "%s" --split train ' ...
         '--episode-index %d --output "%s" --export-only'], ...
        pythonCommand, ...
        pythonExporter, ...
        datasetRoot, ...
        episodeIndex, ...
        outputBase);

    [status, commandOutput] = system(command);

    assert(status == 0, ...
        ['Failed to export the recorded NPZ trajectory.\n' ...
         'Command output:\n%s'], ...
        commandOutput);
end

assert(isfile(dataFile), ...
    'Missing trajectory CSV after NPZ export:\n%s', dataFile);

%% Read and validate the recorded trajectory

T = readtable(dataFile, 'TextType', 'string');

requiredVariables = [ ...
    "episode_id", ...
    "source_shard", ...
    "time_s", ...
    "uav_id", ...
    "x_m", ...
    "y_m", ...
    "z_m" ...
];

missingVariables = setdiff( ...
    requiredVariables, string(T.Properties.VariableNames));

assert(isempty(missingVariables), ...
    'Trajectory CSV is missing columns: %s', ...
    strjoin(missingVariables, ', '));

episodeIds = unique(T.episode_id);
sourceShards = unique(T.source_shard);

assert(numel(episodeIds) == 1, ...
    'Expected one recorded episode but found %d.', numel(episodeIds));

assert(numel(sourceShards) == 1, ...
    'Expected one source shard but found %d.', numel(sourceShards));

timeValues = unique(T.time_s, 'sorted');
uavIds = unique(T.uav_id, 'sorted');

nTime = numel(timeValues);
nUav = numel(uavIds);

assert(nTime > 1, 'The selected trajectory has fewer than two time steps.');
assert(nUav == 8, 'Expected 8 UAVs but found %d.', nUav);
assert(height(T) == nTime * nUav, ...
    'Expected %d time-UAV rows but found %d.', ...
    nTime * nUav, height(T));

positions = nan(nTime, nUav, 3);

for uavIndex = 1:nUav
    rowMask = T.uav_id == uavIds(uavIndex);
    current = T(rowMask, :);
    [currentTimes, order] = sort(current.time_s);
    current = current(order, :);

    assert(isequal(currentTimes, timeValues), ...
        'Time grid differs for UAV %d.', uavIds(uavIndex));

    positions(:, uavIndex, 1) = current.x_m;
    positions(:, uavIndex, 2) = current.y_m;
    positions(:, uavIndex, 3) = current.z_m;
end

assert(all(isfinite(positions(:))), ...
    'The recorded trajectory contains non-finite coordinates.');

centroid = squeeze(mean(positions, 2));
timeStep = median(diff(timeValues));
durationS = timeValues(end) + timeStep;

manifest = jsondecode(fileread(manifestFile));

assert(isfield(manifest, 'config') && ...
       isfield(manifest.config, 'isac') && ...
       isfield(manifest.config.isac, 'anchors_m'), ...
    'The training manifest does not contain ISAC anchor coordinates.');

anchors = double(manifest.config.isac.anchors_m);

%% Visual contract

% One navy hue encodes all trajectories. Line weight, line style, and
% markers distinguish UAV paths, centroid, endpoints, and ISAC anchors.
inkColor = [7, 31, 63] / 255;
pathColor = [73, 98, 122] / 255;
gridColor = [220, 220, 220] / 255;
backgroundColor = [1, 1, 1];
anchorColor = [77, 77, 77] / 255;
formationColor = [138, 154, 167] / 255;

fig = figure( ...
    'Color', backgroundColor, ...
    'Units', 'centimeters', ...
    'Position', [2, 2, 12.8, 8.6]);

layout = tiledlayout( ...
    fig, 1, 1, ...
    'TileSpacing', 'compact', ...
    'Padding', 'compact');

%% Single-panel top view of the training trajectory

topAxes = nexttile(layout, 1);
hold(topAxes, 'on');
box(topAxes, 'on');

for uavIndex = 1:nUav
    plot( ...
        topAxes, ...
        positions(:, uavIndex, 1), ...
        positions(:, uavIndex, 2), ...
        'Color', pathColor, ...
        'LineWidth', 0.85, ...
        'HandleVisibility', 'off');

    plot( ...
        topAxes, ...
        positions(1, uavIndex, 1), ...
        positions(1, uavIndex, 2), ...
        'o', ...
        'Color', inkColor, ...
        'MarkerFaceColor', backgroundColor, ...
        'MarkerSize', 4.5, ...
        'LineWidth', 0.9, ...
        'HandleVisibility', 'off');

    plot( ...
        topAxes, ...
        positions(end, uavIndex, 1), ...
        positions(end, uavIndex, 2), ...
        'x', ...
        'Color', inkColor, ...
        'MarkerSize', 5.0, ...
        'LineWidth', 1.0, ...
        'HandleVisibility', 'off');
end

plot( ...
    topAxes, centroid(:, 1), centroid(:, 2), ...
    '--', ...
    'Color', inkColor, ...
    'LineWidth', 2.0, ...
    'HandleVisibility', 'off');

drawFormationFrame( ...
    topAxes, squeeze(positions(1, :, :)), ...
    ':', formationColor);

drawFormationFrame( ...
    topAxes, squeeze(positions(end, :, :)), ...
    '-', formationColor);

scatter( ...
    topAxes, ...
    anchors(:, 1), anchors(:, 2), ...
    30, '^', ...
    'MarkerEdgeColor', anchorColor, ...
    'MarkerFaceColor', backgroundColor, ...
    'LineWidth', 0.9, ...
    'HandleVisibility', 'off');

coordinateSpan = squeeze( ...
    max(positions(:, :, 1:2), [], [1, 2]) - ...
    min(positions(:, :, 1:2), [], [1, 2]));

labelOffset = [ ...
    0.025 * coordinateSpan(1), ...
    max(0.035 * coordinateSpan(2), 0.8) ...
];

text( ...
    topAxes, ...
    centroid(1, 1) + labelOffset(1), ...
    centroid(1, 2) + labelOffset(2), ...
    sprintf('Start (%.0f s)', timeValues(1)), ...
    'Color', inkColor, ...
    'FontSize', 8, ...
    'FontName', 'Times New Roman', ...
    'HorizontalAlignment', 'left');

text( ...
    topAxes, ...
    centroid(end, 1) - labelOffset(1), ...
    centroid(end, 2) - labelOffset(2), ...
    sprintf('End (%.0f s)', durationS), ...
    'Color', inkColor, ...
    'FontSize', 8, ...
    'FontName', 'Times New Roman', ...
    'HorizontalAlignment', 'right');

xlabel(topAxes, '$x$ (m)', 'Interpreter', 'latex');
ylabel(topAxes, '$y$ (m)', 'Interpreter', 'latex');

styleAxes(topAxes, backgroundColor, gridColor);
axis(topAxes, 'equal');

addAxisMargin( ...
    topAxes, ...
    [reshape(positions(:, :, 1), [], 1); anchors(:, 1)], ...
    [reshape(positions(:, :, 2), [], 1); anchors(:, 2)], ...
    0.045);

%% Standard boxed legend

legendHandles = gobjects(5, 1);

legendHandles(1) = plot( ...
    topAxes, nan, nan, '-', ...
    'Color', pathColor, ...
    'LineWidth', 1.1);

legendHandles(2) = plot( ...
    topAxes, nan, nan, '--', ...
    'Color', inkColor, ...
    'LineWidth', 2.0);

legendHandles(3) = plot( ...
    topAxes, nan, nan, 'o', ...
    'Color', inkColor, ...
    'MarkerFaceColor', backgroundColor, ...
    'MarkerSize', 5.5, ...
    'LineWidth', 1.0);

legendHandles(4) = plot( ...
    topAxes, nan, nan, 'x', ...
    'Color', inkColor, ...
    'MarkerSize', 6.0, ...
    'LineWidth', 1.1);

legendHandles(5) = plot( ...
    topAxes, nan, nan, '^', ...
    'Color', anchorColor, ...
    'MarkerFaceColor', backgroundColor, ...
    'MarkerSize', 5.5, ...
    'LineWidth', 1.0);

legendLabels = { ...
    'UAV trajectories', ...
    'Swarm centroid', ...
    'Initial position', ...
    'Final position', ...
    'ISAC BS' ...
};

legendHandle = legend( ...
    topAxes, legendHandles, legendLabels, ...
    'Location', 'northeast', ...
    'Orientation', 'vertical', ...
    'NumColumns', 1, ...
    'FontName', 'Times New Roman', ...
    'FontSize', 8, ...
    'TextColor', inkColor, ...
    'Color', 'white', ...
    'EdgeColor', [0.25, 0.25, 0.25], ...
    'LineWidth', 0.8, ...
    'Box', 'on');

if isprop(legendHandle, 'ItemTokenSize')
    legendHandle.ItemTokenSize = [22, 15];
end

hold(topAxes, 'off');

%% Export

exportgraphics( ...
    fig, [outputBase, '.png'], ...
    'Resolution', 600, ...
    'BackgroundColor', backgroundColor);

exportgraphics( ...
    fig, [outputBase, '.pdf'], ...
    'ContentType', 'vector', ...
    'BackgroundColor', backgroundColor);

savefig(fig, [outputBase, '.fig']);

try
    exportgraphics( ...
        fig, [outputBase, '.svg'], ...
        'ContentType', 'vector', ...
        'BackgroundColor', backgroundColor);
catch exportError
    warning('SVG export was skipped: %s', exportError.message);
end

fprintf('Recorded episode\n%s\n\n', episodeIds(1));
fprintf('Source shard\n%s\n\n', sourceShards(1));
fprintf('Trajectory data\n%s\n\n', dataFile);
fprintf('Figure prefix\n%s\n', outputBase);

%% Local helpers

function drawFormationFrame(ax, frame, lineStyle, formationColor)

edges = inferFormationEdges(frame, 12);

for edgeIndex = 1:size(edges, 1)
    first = edges(edgeIndex, 1);
    second = edges(edgeIndex, 2);

    plot( ...
        ax, ...
        frame([first, second], 1), ...
        frame([first, second], 2), ...
        'Color', formationColor, ...
        'LineStyle', lineStyle, ...
        'LineWidth', 0.85, ...
        'HandleVisibility', 'off');
end

end

function edges = inferFormationEdges(frame, edgeCount)

nPoint = size(frame, 1);
candidates = zeros(nPoint * (nPoint - 1) / 2, 3);
candidateIndex = 0;

for first = 1:nPoint
    for second = first + 1:nPoint
        candidateIndex = candidateIndex + 1;
        candidates(candidateIndex, :) = [ ...
            norm(frame(first, :) - frame(second, :)), ...
            first, ...
            second ...
        ];
    end
end

candidates = sortrows(candidates, 1);
edges = candidates(1:edgeCount, 2:3);

end

function styleAxes(ax, backgroundColor, gridColor)

set( ...
    ax, ...
    'Color', backgroundColor, ...
    'FontName', 'Times New Roman', ...
    'FontSize', 8, ...
    'LineWidth', 0.8, ...
    'TickDir', 'out', ...
    'Layer', 'top', ...
    'GridColor', gridColor, ...
    'GridAlpha', 0.72, ...
    'MinorGridAlpha', 0.35);

grid(ax, 'on');

end

function addAxisMargin(ax, xValues, yValues, fraction)

xMin = min(xValues(:));
xMax = max(xValues(:));
yMin = min(yValues(:));
yMax = max(yValues(:));

xMargin = fraction * max(xMax - xMin, eps);
yMargin = fraction * max(yMax - yMin, eps);

xlim(ax, [xMin - xMargin, xMax + xMargin]);
ylim(ax, [yMin - yMargin, yMax + yMargin]);

end
