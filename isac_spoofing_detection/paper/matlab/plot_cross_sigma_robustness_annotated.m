        ax, ...
        leftArrowX, ...
        sigmaValue - connectorGap, ...
        positionValue, ...
        fullValue, ...
        positionToFullLabel, ...
        'left', ...
        positionToFullColor, ...
        '-', ...
        lineWidth, ...
        fontSize, ...
        xStep)];

annotationHandles = [ ...
    annotationHandles; ...
    drawSigmaComparisonArrow( ...
        ax, ...
