function handles = drawSigmaComparisonArrow( ...
    ax, ...
    arrowX, ...
    dataSideX, ...
    sourceY, ...
    targetY, ...
    labelText, ...
    labelSide, ...
    lineColor, ...
    lineStyle, ...
    lineWidth, ...
    fontSize, ...
    xStep)

% Draw a vertical improvement arrow and two horizontal guide lines.

yLimits = ylim(ax);
yRange = diff(yLimits);
endpointOffset = 0.006 * yRange;

sourceY = sourceY + endpointOffset;
targetY = targetY + endpointOffset;

if targetY >= sourceY

    arrowMarker = '^';

else

    arrowMarker = 'v';

end

handles = gobjects(5, 1);

handles(1) = plot( ...
    ax, ...
    [arrowX, arrowX], ...
    [sourceY, targetY], ...
    'Color', lineColor, ...
    'LineStyle', lineStyle, ...
    'LineWidth', lineWidth, ...
    'Clipping', 'on', ...
    'HandleVisibility', 'off');

handles(2) = plot( ...
    ax, ...
    [arrowX, dataSideX], ...
    [sourceY, sourceY], ...
    'Color', lineColor, ...
    'LineStyle', lineStyle, ...
    'LineWidth', 0.85 * lineWidth, ...
    'Clipping', 'on', ...
    'HandleVisibility', 'off');

handles(3) = plot( ...
    ax, ...
    [arrowX, dataSideX], ...
    [targetY, targetY], ...
    'Color', lineColor, ...
    'LineStyle', lineStyle, ...
    'LineWidth', 0.85 * lineWidth, ...
    'Clipping', 'on', ...
    'HandleVisibility', 'off');

handles(4) = plot( ...
    ax, ...
    arrowX, ...
    targetY, ...
    arrowMarker, ...
    'Color', lineColor, ...
    'MarkerFaceColor', lineColor, ...
    'MarkerSize', 4.0, ...
    'Clipping', 'on', ...
    'HandleVisibility', 'off');

if strcmpi(labelSide, 'left')

    textX = arrowX - 0.055 * xStep;
    horizontalAlignment = 'right';

else

    textX = arrowX + 0.055 * xStep;
    horizontalAlignment = 'left';

end

handles(5) = text( ...
    ax, ...
    textX, ...
    mean([sourceY, targetY]), ...
    labelText, ...
    'HorizontalAlignment', horizontalAlignment, ...
    'VerticalAlignment', 'middle', ...
    'FontName', 'Times New Roman', ...
    'FontSize', fontSize, ...
    'FontWeight', 'bold', ...
    'Color', lineColor, ...
    'Interpreter', 'latex', ...
    'Clipping', 'on', ...
    'HandleVisibility', 'off');

end


function setAxisWithMargin(ax, values, errors, isProbability)

lower = min(values(:) - errors(:));
upper = max(values(:) + errors(:));
span = upper - lower;

if span <= 0
    span = max(abs(upper), 1) * 0.1;
end

lower = max(0, lower - 0.12 * span);
upper = upper + 0.12 * span;

if isProbability
    upper = min(1, upper);
end

ylim(ax, [lower, upper]);

end
