%% Multi-trajectory generalization under three feature configurations

clear;
clc;
close all;

%% Paths

scriptDir = fileparts(mfilename('fullpath'));

if isempty(scriptDir)
    scriptDir = pwd;
end

projectRoot = fileparts(fileparts(scriptDir));

experimentRoot = fullfile( ...
    projectRoot, ...
    'experimentsCubic', ...
    'mlp16_objective_fa_only');

dataFile = fullfile( ...
    experimentRoot, ...
    'trajectory_generalization_summary', ...
    'trajectory_generalization_runs.csv');

figureOutputDir = fullfile( ...
    projectRoot, ...
    'paper', ...
    'generated_assets', ...
    'figures');

dataOutputDir = fullfile( ...
    projectRoot, ...
    'paper', ...
    'generated_assets', ...
    'data');

if ~isfolder(figureOutputDir)
    mkdir(figureOutputDir);
end

if ~isfolder(dataOutputDir)
    mkdir(dataOutputDir);
end

assert(isfile(dataFile), ...
    'Missing trajectory-generalization records:\n%s', ...
    dataFile);

%% Analysis configuration

trajectoryNames = [ ...
    "straight", ...
    "circle", ...
    "helix", ...
    "s_curve" ...
];

trajectoryLabels = { ...
    'Straight', ...
    'Circle', ...
    'Helix', ...
    sprintf('S-curve\n(matched)') ...
};

featureSets = [ ...
    "position_only", ...
    "no_neighbor", ...
    "inter_uav_consistency" ...
];

featureLabels = { ...
    'Position only', ...
    'Local features', ...
    'Proposed' ...
};

expectedSeeds = [ ...
    20260716, ...
    20260717, ...
    20260718 ...
];

metricFields = [ ...
    "event_recall", ...
    "event_precision", ...
    "event_f1", ...
    "delay_mean_s" ...
];

metricTitles = { ...
    '(a) Event Recall', ...
    '(b) Event Precision', ...
    '(c) Event F1', ...
    '(d) Average detection delay' ...
};

metricYLabels = { ...
    'Event Recall', ...
    'Event Precision', ...
    'Event F1', ...
    'Average delay (s)' ...
};

% Feature encoding for print and grayscale reproduction.
barPatterns = { ...
    'cross', ...
    'diagonal', ...
    'solid' ...
};

barEdgeStyles = { ...
    ':', ...
    '--', ...
    '-' ...
};

% Dark blue used for all bar edges, hatch patterns, and solid bars.
darkBlue = [0.00, 0.20, 0.45];

%% Read and validate the per-seed experiment records

T = readtable(dataFile, 'TextType', 'string');

requiredVariables = [ ...
    "feature_set", ...
    "scope", ...
    "stratum", ...
    "seed", ...
    metricFields ...
];

missingVariables = setdiff( ...
    requiredVariables, ...
    string(T.Properties.VariableNames));

assert(isempty(missingVariables), ...
    'Missing columns in %s:\n%s', ...
    dataFile, ...
    strjoin(missingVariables, ', '));

T.feature_set = lower(strtrim(string(T.feature_set)));
T.scope = lower(strtrim(string(T.scope)));
T.stratum = lower(strtrim(string(T.stratum)));

T = T( ...
    T.scope == "trajectory" & ...
    ismember(T.stratum, trajectoryNames) & ...
    ismember(T.feature_set, featureSets) & ...
    ismember(T.seed, expectedSeeds), :);

nTrajectory = numel(trajectoryNames);
nFeature = numel(featureSets);
nSeed = numel(expectedSeeds);
nMetric = numel(metricFields);

expectedRows = nTrajectory * nFeature * nSeed;

assert(height(T) == expectedRows, ...
    'Expected %d trajectory-feature-seed rows but found %d.', ...
    expectedRows, ...
    height(T));

%% Collect metric values

% Dimensions:
% trajectory x feature x metric x seed
metricValues = nan( ...
    nTrajectory, ...
    nFeature, ...
    nMetric, ...
    nSeed);

for trajectoryIndex = 1:nTrajectory

    for featureIndex = 1:nFeature

        for seedIndex = 1:nSeed

            rowMask = ...
                T.stratum == trajectoryNames(trajectoryIndex) & ...
                T.feature_set == featureSets(featureIndex) & ...
                T.seed == expectedSeeds(seedIndex);

            assert(sum(rowMask) == 1, ...
                ['Expected one row for trajectory=%s, feature=%s, ' ...
                 'and seed=%d.'], ...
                trajectoryNames(trajectoryIndex), ...
                featureSets(featureIndex), ...
                expectedSeeds(seedIndex));

            for metricIndex = 1:nMetric

                metricValues( ...
                    trajectoryIndex, ...
                    featureIndex, ...
                    metricIndex, ...
                    seedIndex) = ...
                    T.(metricFields(metricIndex))(rowMask);

            end

        end

    end

end

assert(all(isfinite(metricValues(:))), ...
    'At least one trajectory metric is not finite.');

metricMeans = mean(metricValues, 4);
metricStds = std(metricValues, 0, 4);

%% Export the exact rows used by the figure

selectedOutputFile = fullfile( ...
    dataOutputDir, ...
    'fig_unseen_trajectory_generalization_data.csv');

selectedTable = T(:, cellstr(requiredVariables));

selectedTable.source_csv = ...
    repmat(string(dataFile), height(selectedTable), 1);

writetable(selectedTable, selectedOutputFile);

%% Export the mean and sample standard deviation

nSummaryRows = nTrajectory * nFeature;

rowTrajectory = strings(nSummaryRows, 1);
rowTrajectoryRole = strings(nSummaryRows, 1);
rowFeature = strings(nSummaryRows, 1);
rowFeatureLabel = strings(nSummaryRows, 1);

summaryValues = nan(nSummaryRows, 2 * nMetric);

rowIndex = 0;

for trajectoryIndex = 1:nTrajectory

    for featureIndex = 1:nFeature

        rowIndex = rowIndex + 1;

        rowTrajectory(rowIndex) = ...
            trajectoryNames(trajectoryIndex);

        rowFeature(rowIndex) = ...
            featureSets(featureIndex);

        rowFeatureLabel(rowIndex) = ...
            featureLabels{featureIndex};

        if trajectoryNames(trajectoryIndex) == "s_curve"

            rowTrajectoryRole(rowIndex) = ...
                "matched_reference";

        else

            rowTrajectoryRole(rowIndex) = ...
                "unseen_type";

        end

        for metricIndex = 1:nMetric

            summaryValues( ...
                rowIndex, ...
                2 * metricIndex - 1) = ...
                metricMeans( ...
                    trajectoryIndex, ...
                    featureIndex, ...
                    metricIndex);

            summaryValues( ...
                rowIndex, ...
                2 * metricIndex) = ...
                metricStds( ...
                    trajectoryIndex, ...
                    featureIndex, ...
                    metricIndex);

        end

    end

end

summaryTable = table( ...
    rowTrajectory, ...
    rowTrajectoryRole, ...
    rowFeature, ...
    rowFeatureLabel, ...
    summaryValues(:, 1), ...
    summaryValues(:, 2), ...
    summaryValues(:, 3), ...
    summaryValues(:, 4), ...
    summaryValues(:, 5), ...
    summaryValues(:, 6), ...
    summaryValues(:, 7), ...
    summaryValues(:, 8), ...
    repmat(string(dataFile), nSummaryRows, 1), ...
    'VariableNames', { ...
    'trajectory', ...
    'trajectory_role', ...
    'feature_set', ...
    'feature_label', ...
    'event_recall_mean', ...
    'event_recall_sample_std', ...
    'event_precision_mean', ...
    'event_precision_sample_std', ...
    'event_f1_mean', ...
    'event_f1_sample_std', ...
    'delay_mean_s_mean', ...
    'delay_mean_s_sample_std', ...
    'source_csv' ...
});

summaryOutputFile = fullfile( ...
    dataOutputDir, ...
    'fig_unseen_trajectory_generalization_summary.csv');

writetable(summaryTable, summaryOutputFile);

%% Plot

fig = figure( ...
    'Color', 'w', ...
    'Units', 'centimeters', ...
    'Position', [2, 2, 17.8, 12.2]);

layout = tiledlayout( ...
    fig, ...
    2, ...
    2, ...
    'TileSpacing', 'compact', ...
    'Padding', 'compact');

axesHandles = gobjects(nMetric, 1);

for metricIndex = 1:nMetric

    ax = nexttile(layout, metricIndex);
    axesHandles(metricIndex) = ax;

    hold(ax, 'on');
    box(ax, 'on');
    grid(ax, 'off');

    values = metricMeans(:, :, metricIndex);

    bars = bar( ...
        ax, ...
        1:nTrajectory, ...
        values, ...
        'grouped');

    for featureIndex = 1:nFeature

        % Position only / Local features:
        % white interior with dark-blue hatch patterns.
        bars(featureIndex).FaceColor = 'w';
        bars(featureIndex).EdgeColor = darkBlue;
        bars(featureIndex).LineStyle = ...
            barEdgeStyles{featureIndex};
        bars(featureIndex).LineWidth = 0.9;

        % Proposed:
        % solid dark-blue bar.
        if featureIndex == nFeature

            bars(featureIndex).FaceColor = darkBlue;
            bars(featureIndex).EdgeColor = darkBlue;
            bars(featureIndex).LineStyle = '-';
            bars(featureIndex).LineWidth = 1.0;

        end

        xPositions = groupedBarPositions( ...
            nTrajectory, ...
            nFeature, ...
            featureIndex);

        drawBarPattern( ...
            ax, ...
            xPositions, ...
            values(:, featureIndex), ...
            nFeature, ...
            barPatterns{featureIndex}, ...
            darkBlue);

    end

    % Separate unseen trajectories from matched S-curve.
    xline( ...
        ax, ...
        3.5, ...
        ':', ...
        'Color', [0.65, 0.65, 0.65], ...
        'LineWidth', 0.9, ...
        'HandleVisibility', 'off');

    set( ...
        ax, ...
        'XTick', 1:nTrajectory, ...
        'XTickLabel', trajectoryLabels, ...
        'XLim', [0.45, nTrajectory + 0.55], ...
        'Color', 'w', ...
        'FontName', 'Times New Roman', ...
        'FontSize', 8, ...
        'LineWidth', 0.75, ...
        'TickDir', 'out', ...
        'Layer', 'top');

    ylabel( ...
        ax, ...
        metricYLabels{metricIndex}, ...
        'FontName', 'Times New Roman');

    title( ...
        ax, ...
        metricTitles{metricIndex}, ...
        'FontName', 'Times New Roman', ...
        'FontSize', 9, ...
        'FontWeight', 'normal');

    if metricIndex <= 3

        ylim(ax, [0, 1.02]);

    else

        setAxisWithMargin( ...
            ax, ...
            values, ...
            zeros(size(values)), ...
            false);

    end

    hold(ax, 'off');

end

