%% Local helpers

function positions = groupedBarPositions( ...
    nGroups, ...
    nBars, ...
    barIndex)

groupWidth = min( ...
    0.8, ...
    nBars / (nBars + 1.5));

positions = ...
    (1:nGroups) - ...
    groupWidth / 2 + ...
    (2 * barIndex - 1) * ...
    groupWidth / (2 * nBars);

end

function drawBarPattern( ...
    ax, ...
    xPositions, ...
    heights, ...
    nBars, ...
    patternName, ...
    lineColor)

if strcmp(patternName, 'solid')
    return;
end

groupWidth = min( ...
    0.8, ...
    nBars / (nBars + 1.5));

barWidth = ...
    0.82 * groupWidth / nBars;

halfWidth = ...
    barWidth / 2;

for barIndex = 1:numel(xPositions)

    center = xPositions(barIndex);
    height = heights(barIndex);

    if ~isfinite(height) || height <= 0
        continue;
    end

    left = center - halfWidth;
    right = center + halfWidth;

    drawDiagonalFamily( ...
        ax, ...
        left, ...
        right, ...
        0, ...
        height, ...
        1, ...
        lineColor, ...
        0.45);

    if strcmp(patternName, 'cross')

        drawDiagonalFamily( ...
            ax, ...
            left, ...
            right, ...
            0, ...
            height, ...
            -1, ...
            lineColor, ...
            0.45);

    end

end

end

function drawDiagonalFamily( ...
    ax, ...
    left, ...
    right, ...
    bottom, ...
    top, ...
    direction, ...
    lineColor, ...
    lineWidth)

offsets = -0.75:0.25:0.75;

for offsetIndex = 1:numel(offsets)

    offset = offsets(offsetIndex);

    if direction > 0

        xStart = max(0, -offset);
        xEnd = min(1, 1 - offset);

        yStart = xStart + offset;
        yEnd = xEnd + offset;

    else

        xStart = max(0, offset);
        xEnd = min(1, 1 + offset);

        yStart = 1 - xStart + offset;
        yEnd = 1 - xEnd + offset;

    end

    if xEnd <= xStart
        continue;
    end

    xCoordinates = ...
        left + ...
        [xStart, xEnd] * ...
        (right - left);

    yCoordinates = ...
        bottom + ...
        [yStart, yEnd] * ...
        (top - bottom);

    plot( ...
        ax, ...
        xCoordinates, ...
        yCoordinates, ...
        'Color', lineColor, ...
        'LineWidth', lineWidth, ...
        'HandleVisibility', 'off');

end

end

function setAxisWithMargin( ...
    ax, ...
    values, ...
    errors, ...
    isProbability)

upper = max(values(:) + errors(:));

if upper <= 0
    upper = 1;
end

upper = 1.12 * upper;

if isProbability
    upper = min(1, upper);
end

ylim(ax, [0, upper]);

end