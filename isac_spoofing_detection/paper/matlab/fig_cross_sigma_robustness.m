%% Cross-sigma_A robustness under three feature configurations

clear;
clc;
close all;

%% Paths

scriptDir = fileparts(mfilename('fullpath'));

if isempty(scriptDir)
    scriptDir = pwd;
end

projectRoot = fileparts(fileparts(scriptDir));
experimentRoot = fullfile( ...
    projectRoot, 'experimentsCubic', 'mlp16_objective_fa_only');

dataFile = fullfile( ...
    experimentRoot, ...
    'cross_rcs_feature_comparison', ...
    'cross_rcs_overall_per_seed.csv');

figureOutputDir = fullfile( ...
    projectRoot, 'paper', 'generated_assets', 'figures');

dataOutputDir = fullfile( ...
    projectRoot, 'paper', 'generated_assets', 'data');

if ~isfolder(figureOutputDir)
    mkdir(figureOutputDir);
end

if ~isfolder(dataOutputDir)
    mkdir(dataOutputDir);
end

assert(isfile(dataFile), ...
    'Missing cross-sigma_A record file:\n%s', dataFile);

%% Analysis configuration

sigmaValues = [3, 6, 9, 12, 15, 18, 21, 24];
trainingSigma = 6;

featureSets = [ ...
    "position_only", ...
    "no_neighbor", ...
    "inter_uav_consistency" ...
];

featureLabels = { ...
    'Position only', ...
    'Local features', ...
    'Proposed' ...
};

expectedSeeds = [20260716, 20260717, 20260718];

metricFields = [ ...
    "event_recall", ...
    "event_precision", ...
    "event_f1", ...
    "delay_mean_s" ...
];

metricYLabels = { ...
    'Event Recall', ...
    'Event Precision', ...
    'Event F1', ...
    'Average delay (s)' ...
};

% The main-paper figure uses the two claim-relevant metrics. Recall and
% Precision are still read, validated, aggregated, and exported below.
plotMetricIndices = [3, 4];

panelTitles = { ...
    '(a) Event F1', ...
    '(b) Average detection delay' ...
};

colors = [ ...
    0.0000, 0.4470, 0.7410
    0.8500, 0.3250, 0.0980
    0.0000, 0.5000, 0.4500
];

lineStyles = {'--', '-.', '-'};
markers = {'o', 's', '^'};

%% Read and validate the per-seed experiment records

T = readtable(dataFile, 'TextType', 'string');

requiredVariables = [ ...
    "test_rcs", ...
    "feature_set", ...
    "training_seed", ...
    metricFields ...
];

missingVariables = setdiff( ...
    requiredVariables, string(T.Properties.VariableNames));

assert(isempty(missingVariables), ...
    'Missing columns in %s:\n%s', ...
    dataFile, strjoin(missingVariables, ', '));

T.feature_set = lower(strtrim(string(T.feature_set)));

keepRows = ...
    ismember(T.test_rcs, sigmaValues) & ...
    ismember(T.feature_set, featureSets) & ...
    ismember(T.training_seed, expectedSeeds);

T = T(keepRows, :);

nSigma = numel(sigmaValues);
nFeature = numel(featureSets);
nSeed = numel(expectedSeeds);
nMetric = numel(metricFields);

expectedRows = nSigma * nFeature * nSeed;

assert(height(T) == expectedRows, ...
    'Expected %d records but found %d.', expectedRows, height(T));

% Dimensions are sigma_A x feature x metric x seed.
metricValues = nan(nSigma, nFeature, nMetric, nSeed);

for sigmaIndex = 1:nSigma
    for featureIndex = 1:nFeature
        for seedIndex = 1:nSeed

            rowMask = ...
                T.test_rcs == sigmaValues(sigmaIndex) & ...
                T.feature_set == featureSets(featureIndex) & ...
                T.training_seed == expectedSeeds(seedIndex);

            assert(sum(rowMask) == 1, ...
                ['Expected one record for sigma_A=%g, feature=%s, ' ...
                 'seed=%d but found %d.'], ...
                sigmaValues(sigmaIndex), ...
                featureSets(featureIndex), ...
                expectedSeeds(seedIndex), ...
                sum(rowMask));

            for metricIndex = 1:nMetric
                metricValues( ...
                    sigmaIndex, featureIndex, metricIndex, seedIndex) = ...
                    T.(metricFields(metricIndex))(rowMask);
            end
        end
    end
end

assert(all(isfinite(metricValues(:))), ...
    'At least one selected metric is not finite.');

metricMeans = mean(metricValues, 4);
metricStds = std(metricValues, 0, 4);

%% Export all four metrics for traceability

nSummaryRows = nSigma * nFeature;
rowSigma = zeros(nSummaryRows, 1);
rowFeature = strings(nSummaryRows, 1);
rowFeatureLabel = strings(nSummaryRows, 1);
rowIndex = 0;

summaryValues = nan(nSummaryRows, 2 * nMetric);

for sigmaIndex = 1:nSigma
    for featureIndex = 1:nFeature
        rowIndex = rowIndex + 1;
        rowSigma(rowIndex) = sigmaValues(sigmaIndex);
        rowFeature(rowIndex) = featureSets(featureIndex);
        rowFeatureLabel(rowIndex) = featureLabels{featureIndex};

        for metricIndex = 1:nMetric
            summaryValues(rowIndex, 2 * metricIndex - 1) = ...
                metricMeans(sigmaIndex, featureIndex, metricIndex);
            summaryValues(rowIndex, 2 * metricIndex) = ...
                metricStds(sigmaIndex, featureIndex, metricIndex);
        end
    end
end

summaryTable = table( ...
    rowSigma, rowFeature, rowFeatureLabel, ...
    summaryValues(:, 1), summaryValues(:, 2), ...
    summaryValues(:, 3), summaryValues(:, 4), ...
    summaryValues(:, 5), summaryValues(:, 6), ...
    summaryValues(:, 7), summaryValues(:, 8), ...
    repmat(string(dataFile), nSummaryRows, 1), ...
    'VariableNames', { ...
    'sigma_A', 'feature_set', 'feature_label', ...
    'event_recall_mean', 'event_recall_sample_std', ...
    'event_precision_mean', 'event_precision_sample_std', ...
    'event_f1_mean', 'event_f1_sample_std', ...
    'delay_mean_s_mean', 'delay_mean_s_sample_std', ...
    'source_csv'});

summaryOutputFile = fullfile( ...
    dataOutputDir, 'fig_cross_sigma_robustness_data.csv');

writetable(summaryTable, summaryOutputFile);

%% Plot

fig = figure( ...
    'Color', 'w', ...
    'Units', 'centimeters', ...
    'Position', [2, 2, 17.8, 7.2]);

layout = tiledlayout( ...
    fig, 1, 2, ...
    'TileSpacing', 'compact', ...
    'Padding', 'compact');

legendHandles = gobjects(nFeature, 1);
firstAxes = [];

for plotIndex = 1:numel(plotMetricIndices)

    metricIndex = plotMetricIndices(plotIndex);

    ax = nexttile(layout, plotIndex);

    if isempty(firstAxes)
        firstAxes = ax;
    end

    hold(ax, 'on');
    box(ax, 'on');
    grid(ax, 'on');

    for featureIndex = 1:nFeature

        values = squeeze( ...
            metricMeans(:, featureIndex, metricIndex));

        errors = squeeze( ...
            metricStds(:, featureIndex, metricIndex));

        lineWidth = 1.25;
        markerFaceColor = 'w';

        if featureIndex == nFeature
            lineWidth = 1.85;
            markerFaceColor = colors(featureIndex, :);
        end

        plotHandle = errorbar( ...
            ax, sigmaValues, values, errors, ...
            'Color', colors(featureIndex, :), ...
            'LineStyle', lineStyles{featureIndex}, ...
            'Marker', markers{featureIndex}, ...
            'MarkerSize', 5.0, ...
            'MarkerFaceColor', markerFaceColor, ...
            'MarkerEdgeColor', colors(featureIndex, :), ...
            'LineWidth', lineWidth, ...
            'CapSize', 4);

        if plotIndex == 1
            legendHandles(featureIndex) = plotHandle;
        end
    end

    if plotIndex == 1
        xline( ...
            ax, trainingSigma, ':', ...
            'Training condition', ...
            'Color', [0.30, 0.30, 0.30], ...
            'LineWidth', 1.0, ...
            'LabelVerticalAlignment', 'bottom', ...
            'LabelHorizontalAlignment', 'left', ...
            'FontName', 'Times New Roman', ...
            'FontSize', 7.5, ...
            'HandleVisibility', 'off');
    else
        xline( ...
            ax, trainingSigma, ':', ...
            'Color', [0.30, 0.30, 0.30], ...
            'LineWidth', 1.0, ...
            'HandleVisibility', 'off');
    end

    set( ...
        ax, ...
        'XTick', sigmaValues, ...
        'XLim', [min(sigmaValues) - 1, max(sigmaValues) + 1], ...
        'FontName', 'Times New Roman', ...
        'FontSize', 8, ...
        'LineWidth', 0.75, ...
        'TickDir', 'out', ...
        'GridAlpha', 0.16, ...
        'MinorGridAlpha', 0.08, ...
        'Layer', 'top');

    xlabel(ax, '$\sigma_A$', 'Interpreter', 'latex');
    ylabel(ax, metricYLabels{metricIndex});

    title( ...
        ax, panelTitles{plotIndex}, ...
        'FontName', 'Times New Roman', ...
        'FontSize', 9, ...
        'FontWeight', 'normal');

    if metricIndex <= 3
        ylim(ax, [0, 1.02]);
    else
        setAxisWithMargin(ax, ...
            metricMeans(:, :, metricIndex), ...
            metricStds(:, :, metricIndex), false);
    end

    hold(ax, 'off');
end

legendHandle = legend( ...
    firstAxes, legendHandles, featureLabels, ...
    'Orientation', 'horizontal', ...
    'NumColumns', nFeature, ...
    'FontName', 'Times New Roman', ...
    'FontSize', 8, ...
    'Box', 'off');

legendHandle.Layout.Tile = 'north';

%% Export

outputBase = fullfile( ...
    figureOutputDir, 'fig_cross_sigma_robustness');

exportgraphics(fig, [outputBase, '.png'], 'Resolution', 600);
exportgraphics(fig, [outputBase, '.pdf'], 'ContentType', 'vector');
savefig(fig, [outputBase, '.fig']);

fprintf('Source records\n%s\n\n', dataFile);
fprintf('Figure data\n%s\n\n', summaryOutputFile);
fprintf('Figure prefix\n%s\n', outputBase);

%% Local helper

function setAxisWithMargin(ax, values, errors, isProbability)

lower = min(values(:) - errors(:));
upper = max(values(:) + errors(:));
span = upper - lower;

if span <= 0
    span = max(abs(upper), 1) * 0.1;
end

lower = max(0, lower - 0.12 * span);
upper = upper + 0.12 * span;

if isProbability
    upper = min(1, upper);
end

ylim(ax, [lower, upper]);

end
