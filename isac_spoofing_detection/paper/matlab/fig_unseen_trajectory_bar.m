%% Local helpers

function upperLimit = niceUpperLimit( ...
    maximumValue, ...
    marginFactor)

    if ~isfinite(maximumValue) || maximumValue <= 0

        upperLimit = 1;
        return;

    end

    rawUpperLimit = ...
        marginFactor * maximumValue;

    orderOfMagnitude = ...
        10 ^ floor(log10(rawUpperLimit));

    normalizedLimit = ...
        rawUpperLimit / orderOfMagnitude;

    niceMultipliers = [ ...
        1, ...
        1.2, ...
        1.5, ...
        2, ...
        2.5, ...
        3, ...
        4, ...
        5, ...
        6, ...
        8, ...
        10];

    multiplierIndex = find( ...
        niceMultipliers >= normalizedLimit, ...
        1, ...
        'first');

    if isempty(multiplierIndex)
        multiplierIndex = numel(niceMultipliers);
    end

    upperLimit = ...
        niceMultipliers(multiplierIndex) * ...
        orderOfMagnitude;

end


function startLegendDrag(legendAxis)

    fig = ancestor( ...
        legendAxis, ...
        'figure');

    if isempty(fig) || ~isgraphics(fig)
        return;
    end

    originalFigureUnits = ...
        fig.Units;

    originalLegendUnits = ...
        legendAxis.Units;

    fig.Units = ...
        'pixels';

    legendAxis.Units = ...
        'pixels';

    startPoint = ...
        fig.CurrentPoint;

    startPosition = ...
        legendAxis.Position;

    dragData.legendAxis = ...
        legendAxis;

    dragData.startPoint = ...
        startPoint;

    dragData.startPosition = ...
        startPosition;

    dragData.originalFigureUnits = ...
        originalFigureUnits;

    dragData.originalLegendUnits = ...
        originalLegendUnits;

    setappdata( ...
        fig, ...
        'LegendDragData', ...
        dragData);

    fig.WindowButtonMotionFcn = ...
        @dragLegend;

    fig.WindowButtonUpFcn = ...
        @stopLegendDrag;

end


function dragLegend(fig, ~)

    if ~isappdata(fig, 'LegendDragData')
        return;
    end

    dragData = ...
        getappdata( ...
            fig, ...
            'LegendDragData');

    legendAxis = ...
        dragData.legendAxis;

    if ~isgraphics(legendAxis)
        return;
    end

    currentPoint = ...
        fig.CurrentPoint;

    displacement = ...
        currentPoint - ...
        dragData.startPoint;

    newPosition = ...
        dragData.startPosition;

    newPosition(1) = ...
        newPosition(1) + ...
        displacement(1);

    newPosition(2) = ...
        newPosition(2) + ...
        displacement(2);

    legendAxis.Position = ...
        newPosition;

    drawnow limitrate;

end


function stopLegendDrag(fig, ~)

    if ~isappdata(fig, 'LegendDragData')

        fig.WindowButtonMotionFcn = '';
        fig.WindowButtonUpFcn = '';

        return;

    end

    dragData = ...
        getappdata( ...
            fig, ...
            'LegendDragData');

    legendAxis = ...
        dragData.legendAxis;

    if isgraphics(legendAxis)

        legendAxis.Units = ...
            dragData.originalLegendUnits;

    end

    fig.Units = ...
        dragData.originalFigureUnits;

    fig.WindowButtonMotionFcn = '';
    fig.WindowButtonUpFcn = '';

    rmappdata( ...
        fig, ...
        'LegendDragData');

end