function hatchHandles = drawLegendHatch( ...
    ax, ...
    patchHandle, ...
    hatchType, ...
    hatchColor, ...
    hatchLineWidth, ...
    nLines)

    %% Obtain the legend-patch bounds

    xData = get( ...
        patchHandle, ...
        'XData');

    yData = get( ...
        patchHandle, ...
        'YData');

    xData = ...
        xData(isfinite(xData));

    yData = ...
        yData(isfinite(yData));

    if isempty(xData) || isempty(yData)

        hatchHandles = ...
            gobjects(0);

        return;

    end

    xMin = ...
        min(xData);

    xMax = ...
        max(xData);

    yMin = ...
        min(yData);

    yMax = ...
        max(yData);

    width = ...
        xMax - xMin;

    height = ...
        yMax - yMin;

    if width <= 0 || height <= 0

        hatchHandles = ...
            gobjects(0);

        return;

    end

    hatchHandles = ...
        gobjects(0);

    %% Draw requested hatch pattern

    switch lower(hatchType)

        case 'horizontal'

            yLevels = linspace( ...
                yMin, ...
                yMax, ...
                nLines + 2);

            yLevels = ...
                yLevels(2:end-1);

            for i = 1:numel(yLevels)

                h = line( ...
                    ax, ...
                    [xMin, xMax], ...
                    [yLevels(i), yLevels(i)], ...
                    'Color', ...
                    hatchColor, ...
                    'LineWidth', ...
                    hatchLineWidth, ...
                    'HandleVisibility', ...
                    'off', ...
                    'HitTest', ...
                    'off', ...
                    'Clipping', ...
                    'on');

                hatchHandles(end + 1, 1) = ...
                    h;

            end

        case 'diagonal'

            hatchHandles = drawDiagonalFamily( ...
                ax, ...
                xMin, ...
                xMax, ...
                yMin, ...
                yMax, ...
                +1, ...
                hatchColor, ...
                hatchLineWidth, ...
                nLines);

        case 'cross'

            h1 = drawDiagonalFamily( ...
                ax, ...
                xMin, ...
                xMax, ...
                yMin, ...
                yMax, ...
                +1, ...
                hatchColor, ...
                hatchLineWidth, ...
                nLines);

            h2 = drawDiagonalFamily( ...
                ax, ...
                xMin, ...
                xMax, ...
                yMin, ...
                yMax, ...
                -1, ...
                hatchColor, ...
                hatchLineWidth, ...
                nLines);

            hatchHandles = [ ...
                h1(:); ...
                h2(:)];

        otherwise

            error( ...
                'Unknown legend hatch type "%s".', ...
                hatchType);

    end

    %% Make hatch lines transparent to mouse interaction

    for i = 1:numel(hatchHandles)

        try

            hatchHandles(i).PickableParts = ...
                'none';

        catch
        end

    end

end


function hatchHandles = drawDiagonalFamily( ...
    ax, ...
    xMin, ...
    xMax, ...
    yMin, ...
    yMax, ...
    direction, ...
    hatchColor, ...
    hatchLineWidth, ...
    nLines)

    %% Draw one family of diagonal lines
    %
    % The lines are generated inside a normalized unit rectangle and then
    % mapped into the actual legend-symbol rectangle. This guarantees that
    % all hatch segments remain inside the legend patch.

    hatchHandles = ...
        gobjects(0);

    if direction > 0

        %% Positive-slope diagonal family

        offsets = linspace( ...
            -0.85, ...
             0.85, ...
             nLines);

        for i = 1:numel(offsets)

            c = ...
                offsets(i);

            points = ...
                zeros(0, 2);

            % Intersection with x = 0

            y = ...
                c;

            if y >= 0 && y <= 1

                points(end + 1, :) = ...
                    [0, y];

            end

            % Intersection with x = 1

            y = ...
                1 + c;

            if y >= 0 && y <= 1

                points(end + 1, :) = ...
                    [1, y];

            end

            % Intersection with y = 0

            x = ...
                -c;

            if x >= 0 && x <= 1

                points(end + 1, :) = ...
                    [x, 0];

            end

            % Intersection with y = 1

            x = ...
                1 - c;

            if x >= 0 && x <= 1

                points(end + 1, :) = ...
                    [x, 1];

            end

            points = ...
                unique( ...
                    points, ...
                    'rows', ...
                    'stable');

            if size(points, 1) < 2
                continue;
            end

            xn = ...
                points(1:2, 1);

            yn = ...
                points(1:2, 2);

            xPlot = ...
                xMin + ...
                xn * (xMax - xMin);

            yPlot = ...
                yMin + ...
                yn * (yMax - yMin);

            h = line( ...
                ax, ...
                xPlot, ...
                yPlot, ...
                'Color', ...
                hatchColor, ...
                'LineWidth', ...
                hatchLineWidth, ...
                'HandleVisibility', ...
                'off', ...
                'HitTest', ...
                'off', ...
                'Clipping', ...
                'on');

            hatchHandles(end + 1, 1) = ...
                h;

        end

    else

        %% Negative-slope diagonal family

        offsets = linspace( ...
            0.15, ...
            1.85, ...
            nLines);

        for i = 1:numel(offsets)

            c = ...
                offsets(i);

            points = ...
                zeros(0, 2);

            % Intersection with x = 0

            y = ...
                c;

            if y >= 0 && y <= 1

                points(end + 1, :) = ...
                    [0, y];

            end

            % Intersection with x = 1

            y = ...
                c - 1;

            if y >= 0 && y <= 1

                points(end + 1, :) = ...
                    [1, y];

            end

            % Intersection with y = 0

            x = ...
                c;

            if x >= 0 && x <= 1

                points(end + 1, :) = ...
                    [x, 0];

            end

            % Intersection with y = 1

            x = ...
                c - 1;

            if x >= 0 && x <= 1

                points(end + 1, :) = ...
                    [x, 1];

            end

            points = ...
                unique( ...
                    points, ...
                    'rows', ...
                    'stable');

            if size(points, 1) < 2
                continue;
            end

            xn = ...
                points(1:2, 1);

            yn = ...
                points(1:2, 2);

            xPlot = ...
                xMin + ...
                xn * (xMax - xMin);

            yPlot = ...
                yMin + ...
                yn * (yMax - yMin);

            h = line( ...
                ax, ...
                xPlot, ...
                yPlot, ...
                'Color', ...
                hatchColor, ...
                'LineWidth', ...
                hatchLineWidth, ...
                'HandleVisibility', ...
                'off', ...
                'HitTest', ...
                'off', ...
                'Clipping', ...
                'on');

            hatchHandles(end + 1, 1) = ...
                h;

        end

    end

end


function startLegendDrag(legendAxis)

    %% Identify the parent figure

    fig = ancestor( ...
        legendAxis, ...
        'figure');

    if isempty(fig) || ~isgraphics(fig)
        return;
    end

    %% Save original units

    originalFigureUnits = ...
        fig.Units;

    originalLegendUnits = ...
        legendAxis.Units;

    %% Convert both figure and legend to pixel coordinates

    fig.Units = ...
        'pixels';

    legendAxis.Units = ...
        'pixels';

    %% Store the initial mouse and legend positions

    startPoint = ...
        fig.CurrentPoint;

    startPosition = ...
        legendAxis.Position;

    %% Store drag information

    dragData.legendAxis = ...
        legendAxis;

    dragData.startPoint = ...
        startPoint;

    dragData.startPosition = ...
        startPosition;

    dragData.originalFigureUnits = ...
        originalFigureUnits;

    dragData.originalLegendUnits = ...
        originalLegendUnits;

    setappdata( ...
        fig, ...
        'LegendDragData', ...
        dragData);

    %% Enable temporary mouse callbacks

    fig.WindowButtonMotionFcn = ...
        @dragLegend;

    fig.WindowButtonUpFcn = ...
        @stopLegendDrag;

end


function dragLegend(fig, ~)

    %% Retrieve drag information

    if ~isappdata(fig, 'LegendDragData')
        return;
    end

    dragData = ...
        getappdata( ...
            fig, ...
            'LegendDragData');

    legendAxis = ...
        dragData.legendAxis;

    if ~isgraphics(legendAxis)
        return;
    end

    %% Calculate mouse displacement

    currentPoint = ...
        fig.CurrentPoint;

    displacement = ...
        currentPoint - ...
        dragData.startPoint;

    %% Update legend position

    newPosition = ...
        dragData.startPosition;

    newPosition(1) = ...
        newPosition(1) + ...
        displacement(1);

    newPosition(2) = ...
        newPosition(2) + ...
        displacement(2);

    legendAxis.Position = ...
        newPosition;

    drawnow limitrate;

end


function stopLegendDrag(fig, ~)

    %% Retrieve drag information

    if ~isappdata(fig, 'LegendDragData')

        fig.WindowButtonMotionFcn = '';
        fig.WindowButtonUpFcn = '';

        return;

    end

    dragData = ...
        getappdata( ...
            fig, ...
            'LegendDragData');

    legendAxis = ...
        dragData.legendAxis;

    %% Restore original coordinate units

    if isgraphics(legendAxis)

        legendAxis.Units = ...
            dragData.originalLegendUnits;

    end

    fig.Units = ...
        dragData.originalFigureUnits;

    %% Remove temporary callbacks

    fig.WindowButtonMotionFcn = '';
    fig.WindowButtonUpFcn = '';

    rmappdata( ...
        fig, ...
        'LegendDragData');

end
