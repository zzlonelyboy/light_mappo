%% Enable manual dragging of the legend
%
% legendflex creates the legend as an axes object rather than a native
% MATLAB Legend object. The following callbacks allow that axes to be
% dragged manually using the mouse.

set( ...
    legendAxis, ...
    'HitTest', ...
    'on', ...
    'ButtonDownFcn', ...
    @(src, event) startLegendDrag(src));

% PickableParts is available in modern MATLAB versions.

try

    set( ...
        legendAxis, ...
        'PickableParts', ...
        'all');

catch
end

% Disable mouse interception by all children of the legend axes.
%
% This includes:
%   text objects
%   colored patches
%   manually drawn hatch lines
%
% Mouse clicks therefore pass through to legendAxis itself.

legendDescendants = ...
    findall(legendAxis);

for i = 1:numel(legendDescendants)

    if legendDescendants(i) == legendAxis
        continue;
    end

