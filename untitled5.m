            firstIsIncrease, ...
            firstSideIndex, ...
            groupMinimumX, ...
            groupMaximumX, ...
            positionToLocalColor, ...
            '-', ...
            annotationLineWidth, ...
            annotationFontSize, ...
            xRange)];

    annotationHandles = [ ...
        annotationHandles; ...
        drawOneDirectionalComparison( ...
            ax, ...
            xPositions(2), ...
            yPositions(2), ...
            xPositions(3), ...
            yPositions(3), ...
