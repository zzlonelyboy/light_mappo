    yPositions, ...
    positionToLocalLabel, ...
    localToFullLabel, ...
    positionToLocalColor, ...
    localToFullColor, ...
    annotationLineWidth, ...
    annotationFontSize)

    %% Draw two directional comparisons around the weak-attack bar group

    % Increasing comparisons are placed to the left of the bars.
    % Decreasing comparisons are placed to the right of the bars.
    % The first comparison is a solid orange arrow, and the second is a
    % dashed green arrow.

    currentXLimits = ...
        xlim(ax);

    xRange = ...
        diff(currentXLimits);

    annotationHandles = ...
        gobjects(0);

    firstIsIncrease = ...
        yPositions(2) >= yPositions(1);

    secondIsIncrease = ...
        yPositions(3) >= yPositions(2);

    groupMinimumX = ...
        min(xPositions);

    groupMaximumX = ...
        max(xPositions);

