    sideIndex, ...
    groupMinimumX, ...
    groupMaximumX, ...
    lineColor, ...
    lineStyle, ...
    lineWidth, ...
    fontSize, ...
    xRange)

    %% Draw one vertical change arrow with horizontal endpoint guides

    if isIncrease

        bracketX = ...
            groupMinimumX - ...
            (0.055 + 0.055 * (sideIndex - 1)) * xRange;

        textX = ...
            bracketX - 0.010 * xRange;

        textAlignment = ...
            'right';

        arrowMarker = ...
            '^';

    else

        bracketX = ...
            groupMaximumX + ...
            (0.055 + 0.055 * (sideIndex - 1)) * xRange;

        textX = ...
            bracketX + 0.010 * xRange;

        textAlignment = ...
            'left';

        arrowMarker = ...
            'v';

    end

    yLimits = ...
        ylim(ax);

    yRange = ...
        diff(yLimits);

    endpointOffset = ...
        0.010 * yRange;

    sourceY = ...
        sourceY + endpointOffset;

    targetY = ...
        targetY + endpointOffset;

    handles = ...
        gobjects(4, 1);

    handles(1) = plot( ...
        ax, ...
        [bracketX, bracketX], ...
        [sourceY, targetY], ...
        'Color', ...
        lineColor, ...
        'LineStyle', ...
        lineStyle, ...
        'LineWidth', ...
        lineWidth, ...
        'Clipping', ...
        'off', ...
        'HandleVisibility', ...
        'off');

    handles(2) = plot( ...
        ax, ...
        [bracketX, sourceX], ...
        [sourceY, sourceY], ...
        'Color', ...
        lineColor, ...
        'LineStyle', ...
        lineStyle, ...
        'LineWidth', ...
        0.85 * lineWidth, ...
        'Clipping', ...
        'off', ...
        'HandleVisibility', ...
        'off');

