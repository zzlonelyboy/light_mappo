%% Identify the legend patch objects

expectedIndices = ...
    numberOfFeatures + ...
    (1:numberOfFeatures);

useExpectedOrder = ...
    numel(legendObjects) >= ...
    2 * numberOfFeatures;

if useExpectedOrder

    expectedObjects = ...
        legendObjects(expectedIndices);

    useExpectedOrder = ...
        all(isgraphics(expectedObjects, 'patch'));

end

if useExpectedOrder

    legendBarObjects = ...
        expectedObjects(:);

else

    % Compatibility fallback.

    legendBarObjects = findobj( ...
        legendAxis, ...
        'Type', ...
        'patch');

    assert( ...
        numel(legendBarObjects) == numberOfFeatures, ...
        ['Unable to identify the three legend patch objects. ' ...
         'The installed legendflex version returned an ' ...
         'unexpected graphics structure.']);

    % Vertical legend: sort patches from top to bottom.

    yCenters = nan( ...
        numel(legendBarObjects), ...
        1);

    for fi = 1:numel(legendBarObjects)

        yData = get( ...
            legendBarObjects(fi), ...
            'YData');

        yData = ...
            yData(isfinite(yData));

        if isempty(yData)

            yCenters(fi) = ...
                -fi;

        else

            yCenters(fi) = ...
                mean(yData);

        end

    end

    [~, sortOrder] = ...
        sort(yCenters, 'descend');

    legendBarObjects = ...
        legendBarObjects(sortOrder);

end

