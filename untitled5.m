%% Matched-RCS = 6 event performance by attack type and severity
%
% Figure layout
%   Rows represent Random, Replay, and Stealth attacks
%   Columns represent Event Recall, Event Precision, Event F1,
%   and Mean Delay
%   The x-axis represents Weak, Medium, and Strong attack severities
%
% Feature representations
%   Position Only   : blue cross hatch
%   Local Features : orange 45-degree hatch
%   Full Features  : green horizontal hatch
%
% Legend
%   The legend is vertically arranged and initially placed at the
%   upper-right corner of the figure.
%
%   The legend can be manually dragged with the mouse.
%
%   After adjusting the legend position, press any key in the MATLAB
%   Command Window to export the final figure.

clear;
close all;
clc;

%% Check required plotting functions

requiredFunctions = { ...
    'hatchfill2', ...
    'legendflex', ...
    'getpos', ...
    'setpos'};

for i = 1:numel(requiredFunctions)

    assert( ...
        exist(requiredFunctions{i}, 'file') == 2, ...
        ['Required plotting function "%s.m" was not found. ' ...
         'Add the complete plotting package to the MATLAB path.'], ...
        requiredFunctions{i});

end

%% Locate the input and output directories

scriptDir = fileparts(mfilename('fullpath'));

if isempty(scriptDir)
    scriptDir = pwd;
end

% The first candidate supports placing this script under paper/matlab.
% The second candidate is the current local project location.

candidateProjectRoots = { ...
    fileparts(fileparts(scriptDir)), ...
    'D:\Codes\project_spoofing_detect\light_mappo\isac_spoofing_detection'};

projectRoot = '';
dataFile = '';

for candidateIndex = 1:numel(candidateProjectRoots)

    candidateDataFile = fullfile( ...
        candidateProjectRoots{candidateIndex}, ...
        'experimentsCubic', ...
        'mlp16_objective_fa_only', ...
        'cross_rcs_feature_comparison', ...
        'cross_rcs_by_attack_type_severity_summary.csv');

    if isfile(candidateDataFile)

        projectRoot = ...
            candidateProjectRoots{candidateIndex};

        dataFile = ...
            candidateDataFile;

        break;

    end

end


assert( ...
    ~isempty(dataFile), ...
    ['Input file was not found relative to the script or in the ' ...
     'configured local project directory.']);

dataDir = ...
    fileparts(dataFile);

figureDir = fullfile( ...
    dataDir, ...
    'matlab_figures');

if ~isfolder(figureDir)
    mkdir(figureDir);
end

%% Read and validate the input table

T = readtable( ...
    dataFile, ...
    'TextType', ...
    'string');

requiredVariables = { ...
    'test_rcs', ...
    'feature_set', ...
    'attack_type', ...
    'severity', ...
    'event_recall_mean', ...
    'event_precision_mean', ...
    'event_f1_mean', ...
    'delay_mean_s_mean'};

missingVariables = setdiff( ...
    requiredVariables, ...
    T.Properties.VariableNames);

assert( ...
    isempty(missingVariables), ...
    'The input table is missing variables: %s', ...
    strjoin(missingVariables, ', '));

%% Normalize categorical columns

T.feature_set = ...
    lower(strtrim(string(T.feature_set)));

T.attack_type = ...
    lower(strtrim(string(T.attack_type)));

T.severity = ...
    lower(strtrim(string(T.severity)));

if isnumeric(T.test_rcs)

    testRcs = ...
        double(T.test_rcs);

else

    testRcs = ...
        str2double(string(T.test_rcs));

end

assert( ...
    all(isfinite(testRcs)), ...
    'Column "test_rcs" contains invalid values.');

%% Select matched RCS = 6 observations

T = T( ...
    testRcs == 6 & ...
    T.attack_type ~= "mixed", ...
    :);

assert( ...
    ~isempty(T), ...
    'No matched RCS = 6 observations were found.');

%% Plot configuration

attackTypes = [ ...
    "random", ...
    "replay", ...
    "stealth"];

attackLabels = { ...
    'Random', ...
    'Replay', ...
    'Stealth'};

severities = [ ...
    "weak", ...
    "medium", ...
    "strong"];

severityLabels = { ...
    'Weak', ...
    'Medium', ...
    'Strong'};

featureSets = [ ...
    "position_only", ...
    "no_neighbor", ...
    "inter_uav_consistency"];

featureLabels = { ...
    'Position Only', ...
    'Local Features', ...
    'Full Features'};

metricNames = [ ...
    "event_recall_mean", ...
    "event_precision_mean", ...
    "event_f1_mean", ...
    "delay_mean_s_mean"];

metricTitles = { ...
    '(a) Event Recall', ...
    '(b) Event Precision', ...
    '(c) Event F1', ...
    '(d) Mean Delay'};

numberOfAttacks = ...
    numel(attackTypes);

numberOfSeverities = ...
    numel(severities);

numberOfFeatures = ...
    numel(featureSets);

numberOfMetrics = ...
    numel(metricNames);

% Keep the score axes zero-based while removing unnecessary headroom.
% The small margin above 1 leaves space for arrowheads and annotations.

scoreUpperLimit = ...
    1.06;

%% Color configuration

% Keep the original saturated colors.

featureColors = [ ...
      0, 114, 189; ...
    217,  83,  25; ...
    119, 172,  48] / 255;

% Keep the original pale bar backgrounds.

featureFaceColors = ...
    0.74 * ones(size(featureColors)) + ...
    0.26 * featureColors;

% Keep the original darker same-color borders.

featureEdgeColors = ...
    0.72 * featureColors;

%% Hatch configuration

hatchStyles = { ...
    'cross', ...
    'single', ...
    'single'};

hatchAngles = [ ...
    45, ...
    45, ...
     0];

% Hatch density for the actual bars.

barHatchDensity = [ ...
    38, ...
    42, ...
    42];

hatchLineWidth = ...
    0.60;

%% Value-label configuration

% Absolute values above the bars are disabled. The exact values remain
% available from the source CSV and the relative changes of interest are
% shown through the sequential-comparison annotations.

showAbsoluteValueLabels = ...
    false;

scoreValueFormat = ...
    '%.3f';

delayValueFormat = ...
    '%.3f';

valueLabelFontSize = ...
    7.0;

valueLabelGapFraction = ...
    0.010;

% Minimum vertical separation between labels in the same severity group.

valueLabelMinSeparationFraction = ...
    0.050;

valueLabelColor = [ ...
    0.10, ...
    0.10, ...
    0.10];

%% Sequential-comparison annotation configuration

% Show the two sequential comparisons for weak random attacks.
% Upward changes are placed on the left of the weak bar group, whereas
% downward changes are placed on the right.

showSequentialComparisonAnnotations = ...
    true;

positionToLocalAnnotationColor = [ ...
    184, ...
     73, ...
     26] / 255;

localToFullAnnotationColor = [ ...
     92, ...
    135, ...
     39] / 255;

comparisonAnnotationLineWidth = ...
    0.85;

comparisonAnnotationFontSize = ...
    6.8;

%% Assemble all plotting values before drawing

% Dimensions:
%   severity x feature x attack x metric

plotValues = nan( ...
    numberOfSeverities, ...
    numberOfFeatures, ...
    numberOfAttacks, ...
    numberOfMetrics);

for ai = 1:numberOfAttacks

    for si = 1:numberOfSeverities

        for fi = 1:numberOfFeatures

            mask = ...
                T.attack_type == attackTypes(ai) & ...
                T.severity == severities(si) & ...
                T.feature_set == featureSets(fi);

            D = ...
                T(mask, :);

            assert( ...
                height(D) == 1, ...
                ['Expected exactly one row for attack "%s", ' ...
                 'severity "%s", and feature set "%s". ' ...
                 'Found %d rows.'], ...
                attackTypes(ai), ...
                severities(si), ...
                featureSets(fi), ...
                height(D));

            for mi = 1:numberOfMetrics

                metricName = ...
                    char(metricNames(mi));

                value = ...
                    D.(metricName);

                assert( ...
                    isnumeric(value) && ...
                    isscalar(value) && ...
                    isfinite(value), ...
                    ['Metric "%s" must contain one finite numeric value ' ...
                     'for %s, %s, and %s.'], ...
                    metricName, ...
                    attackTypes(ai), ...
                    severities(si), ...
                    featureSets(fi));

                plotValues( ...
                    si, ...
                    fi, ...
                    ai, ...
                    mi) = ...
                    double(value);

            end

        end

    end

end

%% Determine a shared delay-axis range

delayValues = ...
    plotValues(:, :, :, 4);

maximumDelay = ...
    max(delayValues(:));

if maximumDelay <= 0

    delayUpperLimit = ...
        1;

else

    rawUpperLimit = ...
        1.10 * maximumDelay;

    orderOfMagnitude = ...
        10 ^ floor(log10(rawUpperLimit));

    normalizedLimit = ...
        rawUpperLimit / orderOfMagnitude;

    niceMultipliers = [ ...
        1, ...
        1.2, ...
        1.5, ...
        2, ...
        2.5, ...
        3, ...
        4, ...
        5, ...
        6, ...
        8, ...
        10];

    multiplierIndex = find( ...
        niceMultipliers >= normalizedLimit, ...
        1, ...
        'first');

    if isempty(multiplierIndex)

        multiplierIndex = ...
            numel(niceMultipliers);

    end

    delayUpperLimit = ...
        niceMultipliers(multiplierIndex) * ...
        orderOfMagnitude;

end

%% Create the figure

fig = figure( ...
    'Color', ...
    'w', ...
    'Units', ...
    'centimeters', ...
    'Position', ...
    [1, 1, 18.2, 10.8], ...
    'PaperPositionMode', ...
    'auto', ...
    'Renderer', ...
    'painters');

tl = tiledlayout( ...
    fig, ...
    numberOfAttacks, ...
    numberOfMetrics, ...
    'TileSpacing', ...
    'compact', ...
    'Padding', ...
    'compact');

try

    tl.OuterPosition = [ ...
        0.055, ...
        0.055, ...
        0.925, ...
        0.855];

catch

    % OuterPosition may be unavailable in older MATLAB versions.

end

axesHandles = gobjects( ...
    numberOfAttacks, ...
    numberOfMetrics);

x = ...
    1:numberOfSeverities;

%% Draw the subplots

for ai = 1:numberOfAttacks

    for mi = 1:numberOfMetrics

        tileIndex = ...
            (ai - 1) * numberOfMetrics + mi;

        ax = nexttile( ...
            tl, ...
            tileIndex);

        axesHandles(ai, mi) = ...
            ax;

        hold(ax, 'on');

        values = ...
            plotValues(:, :, ai, mi);

        %% Draw grouped bars

        bars = bar( ...
            ax, ...
            x, ...
            values, ...
            'grouped', ...
            'BarWidth', ...
            0.82);

%% Apply bar colors and hatches

for fi = 1:numberOfFeatures

    bars(fi).FaceColor = ...
        featureFaceColors(fi, :);

    bars(fi).EdgeColor = ...
        featureEdgeColors(fi, :);

    bars(fi).LineStyle = ...
        '-';

    bars(fi).LineWidth = ...
        0.90;

    % -------------------------------------------------------------
    % IMPORTANT:
    %
    % The current bar must remain visible to hatchfill2 while the
    % hatch is being created. Therefore HandleVisibility must NOT
    % be set to 'off' before this call.
    % -------------------------------------------------------------

    hatchHandles = hatchfill2( ...
        bars(fi), ...
        hatchStyles{fi}, ...
        'HatchAngle', ...
        hatchAngles(fi), ...
        'HatchDensity', ...
        barHatchDensity(fi), ...
        'HatchColor', ...
        featureColors(fi, :), ...
        'HatchLineWidth', ...
        hatchLineWidth);

    % Hide the auxiliary hatch objects from automatic legend handling.

    if ~isempty(hatchHandles)

        try

            set( ...
                hatchHandles, ...
                'HandleVisibility', ...
                'off');

        catch
        end

    end

    % -------------------------------------------------------------
    % IMPORTANT:
    %
    % Hide THIS bar immediately after hatchfill2 has finished.
    %
    % Do not postpone this operation until all three feature bars
    % have been processed. hatchfill2 manipulates the Children order
    % of the parent axes, and leaving previously processed bars
    % visible can cause the hatch graphics of earlier bars to be
    % disturbed by subsequent hatchfill2 calls.
    %
    % The actual bars are not required for the legend because the
    % legend is constructed later from independent proxy patches.
    % -------------------------------------------------------------

    bars(fi).HandleVisibility = ...
        'off';

end

        %% Configure x-axis

        xlim( ...
            ax, ...
            [0.15, numberOfSeverities + 0.5]);

        xticks( ...
            ax, ...
            x);

        if ai == numberOfAttacks

            xticklabels( ...
                ax, ...
                severityLabels);

            xlabel( ...
                ax, ...
                'Attack Severity');

        else

            xticklabels( ...
                ax, ...
                {});

        end

        %% Configure column titles

        if ai == 1

            title( ...
                ax, ...
                metricTitles{mi}, ...
                'FontWeight', ...
                'bold', ...
                'FontSize', ...
                8.5, ...
                'Interpreter', ...
                'none');

        end

        %% Configure y-axis

        if mi <= 3

            ylim( ...
                ax, ...
                [0, scoreUpperLimit]);

            yticks( ...
                ax, ...
                0:0.2:1.0);

        else

            ylim( ...
                ax, ...
                [0, delayUpperLimit]);

        end

        %% Add collision-aware values above the bars

        currentYLimits = ...
            ylim(ax);

        yRange = ...
            diff(currentYLimits);

        valueLabelOffset = ...
            valueLabelGapFraction * ...
            yRange;

        minimumLabelSeparation = ...
            valueLabelMinSeparationFraction * ...
            yRange;

        if mi <= 3

            valueFormat = ...
                scoreValueFormat;

        else

            valueFormat = ...
                delayValueFormat;

        end

        % Store the center and top position of every bar. Dimensions are
        % severity by feature.

        xPositions = nan( ...
            numberOfSeverities, ...
            numberOfFeatures);

        yPositions = nan( ...
            numberOfSeverities, ...
            numberOfFeatures);

        for fi = 1:numberOfFeatures

            xPositions(:, fi) = ...
                bars(fi).XEndPoints(:);

            yPositions(:, fi) = ...
                bars(fi).YEndPoints(:);

        end

        % Absolute-value labels can be restored by setting
        % showAbsoluteValueLabels to true.

        if showAbsoluteValueLabels

            for si = 1:numberOfSeverities

            labelYPositions = ...
                yPositions(si, :) + ...
                valueLabelOffset;

            [~, labelOrder] = sort( ...
                labelYPositions, ...
                'ascend');

            % Move only labels whose vertical positions are too close.

            for li = 2:numberOfFeatures

                previousIndex = ...
                    labelOrder(li - 1);

                currentIndex = ...
                    labelOrder(li);

                requiredPosition = ...
                    labelYPositions(previousIndex) + ...
                    minimumLabelSeparation;

                labelYPositions(currentIndex) = max( ...
                    labelYPositions(currentIndex), ...
                    requiredPosition);

            end

            % Shift the complete label group downward if its highest label
            % would otherwise exceed the current axis.

            upperLabelMargin = ...
                0.012 * ...
                yRange;

            maximumAllowedPosition = ...
                currentYLimits(2) - ...
                upperLabelMargin;

            highestLabelPosition = ...
                max(labelYPositions);

            if highestLabelPosition > maximumAllowedPosition

                downwardShift = ...
                    highestLabelPosition - ...
                    maximumAllowedPosition;

                labelYPositions = ...
                    labelYPositions - ...
                    downwardShift;

            end

            for fi = 1:numberOfFeatures

                valueString = sprintf( ...
                    valueFormat, ...
                    values(si, fi));

                text( ...
                    ax, ...
                    xPositions(si, fi), ...
                    labelYPositions(fi), ...
                    valueString, ...
                    'HorizontalAlignment', ...
                    'center', ...
                    'VerticalAlignment', ...
                    'bottom', ...
                    'FontName', ...
                    'Times New Roman', ...
                    'FontSize', ...
                    valueLabelFontSize, ...
                    'FontWeight', ...
                    'normal', ...
                    'Color', ...
                    valueLabelColor, ...
                    'Interpreter', ...
                    'none', ...
                    'Clipping', ...
                    'on', ...
                    'HandleVisibility', ...
                    'off');

            end

            end

        end

        %% Highlight the two sequential comparisons under weak random attack

        if showSequentialComparisonAnnotations && ...
                ai == 1

            weakXPositions = ...
                xPositions(1, :);

            weakYPositions = ...
                yPositions(1, :);

            if mi == 1

                % Event Recall
                % Position Only -> Local Features
                positionToLocalValue = ...
                    weakYPositions(2) / ...
                    weakYPositions(1);

                positionToLocalLabel = sprintf( ...
                    '$%.2f\\times$', ...
                    positionToLocalValue);

                % Local Features -> Full Features
                localToFullValue = ...
                    100 * ...
                    (weakYPositions(3) - weakYPositions(2)) / ...
                    weakYPositions(2);

                localToFullLabel = sprintf( ...
                    '$+%.2f\\%%$', ...
                    localToFullValue);

            elseif mi == 2

                % Event Precision
                % Position Only -> Local Features
                positionToLocalValue = ...
                    100 * ...
                    (weakYPositions(2) - weakYPositions(1)) / ...
                    weakYPositions(1);

                positionToLocalLabel = sprintf( ...
                    '$+%.2f\\%%$', ...
                    positionToLocalValue);

                % Local Features -> Full Features
                localToFullValue = ...
                    100 * ...
                    (weakYPositions(3) - weakYPositions(2)) / ...
                    weakYPositions(2);

                localToFullLabel = sprintf( ...
                    '$%.2f\\%%$', ...
                    localToFullValue);

            elseif mi == 3

                % Event F1
                % Position Only -> Local Features
                positionToLocalValue = ...
                    weakYPositions(2) / ...
                    weakYPositions(1);

                positionToLocalLabel = sprintf( ...
                    '$%.2f\\times$', ...
                    positionToLocalValue);

                % Local Features -> Full Features
                localToFullValue = ...
                    100 * ...
                    (weakYPositions(3) - weakYPositions(2)) / ...
                    weakYPositions(2);

                localToFullLabel = sprintf( ...
                    '$+%.2f\\%%$', ...
                    localToFullValue);

            else

                % Mean Delay
                % Position Only -> Local Features
                positionToLocalValue = ...
                    100 * ...
                    (weakYPositions(1) - weakYPositions(2)) / ...
                    weakYPositions(1);

                positionToLocalLabel = sprintf( ...
                    '$-%.2f\\%%$', ...
                    positionToLocalValue);

                % Local Features -> Full Features
                localToFullValue = ...
                    100 * ...
                    (weakYPositions(2) - weakYPositions(3)) / ...
                    weakYPositions(2);

                localToFullLabel = sprintf( ...
                    '$-%.2f\\%%$', ...
                    localToFullValue);

            end

            drawDirectionalComparisons( ...
                ax, ...
                weakXPositions, ...
                weakYPositions, ...
                positionToLocalLabel, ...
                localToFullLabel, ...
                positionToLocalAnnotationColor, ...
                localToFullAnnotationColor, ...
                comparisonAnnotationLineWidth, ...
                comparisonAnnotationFontSize);

        end

        if mi == 1

            ylabel( ...
                ax, ...
                attackLabels{ai}, ...
                'FontWeight', ...
                'bold', ...
                'FontSize', ...
                8.5, ...
                'Interpreter', ...
                'none');

        elseif mi == 4

            ylabel( ...
                ax, ...
                'Seconds');

        end

        %% Configure axis appearance

        grid(ax, 'on');
        box(ax, 'on');

        set( ...
            ax, ...
            'FontName', ...
            'Times New Roman', ...
            'FontSize', ...
            7.8, ...
            'LineWidth', ...
            0.8, ...
            'TickDir', ...
            'out', ...
            'TickLength', ...
            [0.012, 0.012], ...
            'GridAlpha', ...
            0.16, ...
            'XGrid', ...
            'off', ...
            'YGrid', ...
            'on', ...
            'Layer', ...
            'top', ...
            'TickLabelInterpreter', ...
            'none');

        hold(ax, 'off');

    end

end

